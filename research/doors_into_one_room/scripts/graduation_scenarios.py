"""Verify old/new snapshotted triggers against current rent without changing existing rooms."""
import json
from fractions import Fraction
from pathlib import Path

import account_sizes as A
import curve_identities as C

ROOT=Path(__file__).resolve().parent.parent


def main():
    old_read=json.loads((ROOT/'outputs/narrative/current_rent.json').read_text(encoding='utf-8'))
    old_rate=old_read['rows'][0]['model_lamports']//128
    current=A.graduation_rent_lamports()
    old_rent=current*old_rate//A.LAMPORTS_PER_BYTE
    vs=round(C.R_STAR*(C.V_TOK_BRIEF-C.f*C.S)/(C.f*C.S)*C.LAMPORTS)
    vt=int(C.V_TOK_BRIEF*C.DEC);rs=int(C.R_STAR*C.LAMPORTS)
    lines=['<!-- generated by scripts/graduation_scenarios.py -->',
           '# Config trigger snapshots survive a rent/default change','',
           '| room snapshot | trigger (lamports) | sold base units | pool seed base units | retired base units | rent budget | current rent | budget left after rent |',
           '|---|---|---|---|---|---|---|---|']
    results=[]
    for name,budget in [('old room, old trigger',old_rent),('new room, current default',current)]:
        state=C.graduation_quantities(vs,vt,rs,rs+budget)
        assert state['seed']+state['retired']+state['q_g']==10**15
        assert state['rent_budget']>=current
        assert state['price_step_percent']>=0
        curve_price=Fraction(vs*vt,(vt-state['q_g'])**2)
        assert Fraction(rs,state['seed'])>=curve_price>Fraction(rs,state['seed']+1)
        results.append({'room':name,**state,'current_rent':current,'budget_left':budget-current})
        lines.append(f"| {name} | {state['trigger']:,} | {state['q_g']:,} | {state['seed']:,} | "
                     f"{state['retired']:,} | {budget:,} | {current:,} | {budget-current:,} |")
    assert results[0]['seed']!=results[1]['seed']
    lines+=['','Existing rooms retain their copied trigger, curve constants and sold state. '
            'The seed is computed from that state, never from the newest Config default. '
            'Lower runtime rent leaves budget dust for the existing graduation dust path. '
            'If future rent exceeds a room\'s budget, protocol-accrued fees/top-up cover the '
            'shortfall or the transaction fails atomically for retry; no trigger rewrite or '
            'extra reserve debit is allowed. These are exact model checks, not program execution tests.']
    (ROOT/'outputs/graduation_scenarios.md').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    (ROOT/'outputs/graduation_scenarios.json').write_text(json.dumps(results,indent=2)+'\n',encoding='utf-8',newline='\n')
    print('\n'.join(lines))


if __name__=='__main__':
    main()
