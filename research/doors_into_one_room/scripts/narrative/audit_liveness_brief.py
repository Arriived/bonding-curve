"""Audit the brief's room-age claim against the recorded calibration, without new RPC reads.

Usage: python3 scripts/narrative/audit_liveness_brief.py
The existing proxy aggregates earlier SOL-quoted members into a hypothetical room.
Its creation time is the earliest member's launch, not the latest activity time.
"""
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "outputs" / "narrative"
SOL_QUOTES = {"11111111111111111111111111111111", "So11111111111111111111111111111111111111112"}


def load_samples():
    reads = json.loads((OUT / "liveness_reads.json").read_text(encoding="utf-8"))
    quotes = json.loads((OUT / "liveness_quote_mints.json").read_text(encoding="utf-8"))["quote_mint"]
    copies = {c["copy_sig"]: c for c in json.loads((OUT / "copies.json").read_text(encoding="utf-8"))}
    rows = []
    for copy in reads["part_a_copies"]:
        sol_reads = [r for r in copy["reads"] if quotes.get(r["mint"]) in SOL_QUOTES]
        if not sol_reads:
            continue
        members = copies[copy["copy_sig"]]["members"]
        sol_members = [m for m in members if quotes.get(m["mint"]) in SOL_QUOTES]
        assert sol_members, copy["copy_sig"]
        times = [r["time"] for r in sol_reads if r.get("time") is not None]
        rows.append({"age": copy["copy_time"] - min(m["launch_time"] for m in sol_members),
                     "all_member_age": copy["copy_time"] - min(m["launch_time"] for m in members),
                     "idle": copy["copy_time"] - max(times) if times else None})
    return rows


def main():
    rows = load_samples()
    n = len(rows)
    lines = ["<!-- generated by scripts/narrative/audit_liveness_brief.py -->",
             "# Liveness brief correction: room age differs from idle time", "",
             "Source: stored liveness_reads.json, liveness_quote_mints.json and copies.json; "
             "no new on-chain values are introduced. Recorded source slots remain in those files.", "",
             f"SOL-quoted copy population: {n}; with an activity timestamp: "
             f"{sum(r['idle'] is not None for r in rows)}.", "",
             "| metric | median seconds |", "|---|---|",
             f"| room age, earliest earlier SOL-quoted member's launch | {statistics.median(r['age'] for r in rows):g} |",
             f"| room age, earliest earlier member's launch regardless of quote | "
             f"{statistics.median(r['all_member_age'] for r in rows):g} |",
             f"| idle, latest recorded member activity | "
             f"{statistics.median(r['idle'] for r in rows if r['idle'] is not None):g} |", "",
             "The brief's claim that the median target room is one second old confuses "
             "last-activity idle time with room age. The recorded idle statistic also includes "
             "non-trade signatures; it is the original calibration's activity proxy, not a "
             "verified last-trade timestamp.", "",
             "The owner acknowledged this correction and explicitly authorized continuing "
             "with the measured age distribution. The stored copy window alone cannot establish "
             "long-run recall; the age-window sweep is in liveness_table.md."]
    report = "\n".join(lines) + "\n"
    (OUT / "liveness_brief_audit.md").write_text(report, encoding="utf-8", newline="\n")
    print(report)


if __name__ == "__main__":
    main()
