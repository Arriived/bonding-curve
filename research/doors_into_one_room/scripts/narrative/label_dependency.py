"""Separate label-free metadata metrics from semantic estimates in the all-live benchmark.

This groups metadata under the fixed v1 equality rule. It is not a full-gate
replay and supplies no invented reserve, volume, or pool state.
"""
import json

import calibrate_text as T
import matcher as M
from audit_liveness_brief import OUT, ROOT
from calibration_common import ground_truth


def metadata_text_routes(rows):
    roots, faces, routes = {}, {}, []
    for j, row in enumerate(rows):
        if row['nk'] and len(row['nk']) >= M.DEFAULTS['name_equal_min_len']:
            key = ('name', row['nk'])
        elif row['nk'] and row['sk']:
            key = ('identity', row['nk'], row['sk'])
        else:
            key = ('unmatchable', j)
        if key not in roots:
            roots[key] = j
            faces[key] = []
        else:
            # Every group has the same eligible name/identity, so no reserve tie is needed.
            routes.append({'candidate': j, 'root': roots[key], 'earlier_faces': faces[key][:]})
        faces[key].append(j)
    return routes, len(roots)


def main():
    rows = T.load(OUT/'pump_launches.jsonl')
    probability, certain_v, population, labels = ground_truth(rows, ROOT/'scripts/narrative/labels_assistant.csv')
    routes, rooms = metadata_text_routes(rows)
    seen = set()
    uri_v, legacy_uri_v = set(), set()
    for j, row in enumerate(rows):
        if row['uri'] in seen:
            legacy_uri_v.add(j)
            if row['uri']:
                uri_v.add(j)
        seen.add(row['uri'])
    strict_root_uri = []
    uri_containment = []
    automatic_root_identity = []
    uri_judgement_needed = []
    for route in routes:
        a, b = rows[route['root']], rows[route['candidate']]
        auto = T.vkey(a) == T.vkey(b) or (bool(b['uri']) and a['uri'] == b['uri'])
        if route['candidate'] in uri_v:
            if a['uri'] == b['uri']:
                strict_root_uri.append(route)
            if any(rows[i]['uri'] == b['uri'] for i in route['earlier_faces']):
                uri_containment.append(route)
            if auto:
                automatic_root_identity.append(route)
            else:
                uri_judgement_needed.append(route)
    estimated_correct = sum(probability(rows[r['root']], rows[r['candidate']]) for r in routes)
    legacy_uri_correct = sum(probability(rows[r['root']], rows[r['candidate']]) for r in routes
                             if r['candidate'] in legacy_uri_v)
    needed_classes = {label: 0 for label in ('S', 'D', 'U', 'unlabelled')}
    for r in uri_judgement_needed:
        label = labels.get(T.pair_key(rows[r['root']], rows[r['candidate']]), 'unlabelled')
        needed_classes[label] += 1
    report = {
        'scope': 'conditional metadata-only benchmark, all rooms assumed live; no financial state supplied',
        'launches': len(rows), 'routes': len(routes), 'new_rooms': rooms,
        'legacy_expected_vamps': population, 'legacy_definition_certain_vamps': len(certain_v),
        'semantic_precision_estimate': estimated_correct/len(routes),
        'semantic_recall_estimate': estimated_correct/population,
        'empty_uri_launches': sum(not r['uri'] for r in rows),
        'legacy_uri_copy_denominator': len(legacy_uri_v), 'nonempty_uri_copy_denominator': len(uri_v),
        'legacy_uri_estimated_correct_recall': legacy_uri_correct/len(legacy_uri_v),
        'nonempty_uri_copies_routed': sum(r['candidate'] in uri_v for r in routes),
        'root_same_uri_successes': len(strict_root_uri),
        'same_uri_in_room_successes': len(uri_containment),
        'root_identity_or_uri_definition_successes': len(automatic_root_identity),
        'uri_routes_requiring_semantic_judgement': len(uri_judgement_needed),
        'uri_route_judgements': needed_classes,
    }
    (OUT/'label_dependency.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8', newline='\n')
    n = len(uri_v)
    lines = ['<!-- generated by scripts/narrative/label_dependency.py -->', '# Label dependency of reported figures', '',
             '**All figures here are conditional all-live benchmark counts or estimates. None is '
             'a production full-gate precision/recall measurement.** The grouping uses the fixed v1 '
             'folded-name/identity equality rule and no invented financial state. Ordering is the '
             'historical slot/signature benchmark order, not a measured within-slot transaction order.', '',
             '| figure | conditional benchmark value | assistant labels required? |', '|---|---|---|',
             f"| launches / routes / new rooms | {len(rows)} / {len(routes)} / {rooms} | no; metadata-only grouping under the all-live assumption |",
             f"| semantic precision / recall estimate | {report['semantic_precision_estimate']:.2%} / {report['semantic_recall_estimate']:.2%} | yes; same legacy estimator and assistant labels as text_calibration.md |",
             f"| nonempty identical-URI copy cohort | {n} | no; exact string-duplication definition |",
             f"| identical URI to room root | {len(strict_root_uri)}/{n} ({len(strict_root_uri)/n:.2%}) | no; strict URI-group root recovery, not general semantic recall |",
             f"| identical URI in an earlier face of selected room | {len(uri_containment)}/{n} ({len(uri_containment)/n:.2%}) | no; group containment, not proof that the root is the right narrative |",
             f"| root identity-or-URI definition matches in that cohort | {len(automatic_root_identity)}/{n} ({len(automatic_root_identity)/n:.2%}) | no human judgement; depends on the published folding/identity policy |",
             f"| routed URI-cohort cases requiring semantic judgement against the root | {len(uri_judgement_needed)} | yes: "
             + ', '.join(f'{v} {k}' for k,v in needed_classes.items()) + ' |', '',
             '**Correction to the old identical-URI recall claim:** its denominator was selected '
             'without labels, but its numerator scored correctness against the root with the same '
             'label/stratum estimator as other routes. It was not wholly label-independent. The '
             'strict URI metrics above avoid that estimator and name exactly what they count.', '',
             f"The archived text benchmark also groups empty URI strings together: {report['empty_uri_launches']} "
             f"launches have no URI, contributing {len(legacy_uri_v)-n} extra cases to its legacy URI-copy "
             f"denominator of {len(legacy_uri_v)}. Missing URI is not evidence of copied metadata. "
             'The independent nonempty-URI metrics exclude those cases; historical benchmark outputs '
             'are retained with their original definition for comparison.', '',
             'Even a repeated nonempty mutable HTTP URI proves string equality, not identical '
             'historical JSON/image bytes. Folded identity is also a definition, not independent human '
             'confirmation of narrative meaning. All semantic S/D/U labels are assistant judgements '
             'without human review. Their stratum estimates, pessimistic estimates and expected-vamp '
             'denominator depend on those judgements. Raw age/slot counts and fixed-target gate bounds '
             'do not use narrative labels, but retain their disclosed cohort/proxy assumptions.']
    text = '\n'.join(lines)+'\n'
    (OUT/'label_dependency.md').write_text(text, encoding='utf-8', newline='\n')
    print(text)


if __name__ == '__main__':
    main()
