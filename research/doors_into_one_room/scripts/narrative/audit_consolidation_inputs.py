"""Record outcome corrections and the owner's approved snapshot-accounting framing."""
import collections
import json

from audit_liveness_brief import OUT,ROOT


def main():
    rows=[json.loads(line) for line in (OUT/'consolidation_outcomes.jsonl').read_text(encoding='utf-8').splitlines()]
    run=json.loads((OUT/'consolidation_collection.json').read_text(encoding='utf-8'))
    completed=[r for r in rows if r.get('complete') is True]
    sol=[r for r in rows if r.get('sol_quoted') is True]
    report={'launches':len(rows),'statuses':dict(collections.Counter(r['status'] for r in rows)),
        'sol_quoted':len(sol),'non_sol_quoted':sum(r.get('sol_quoted') is False for r in rows),
        'completed_curves':len(completed),
        'completed_with_zero_current_real_quote_reserves':sum(r['real_quote_reserves_raw']==0 for r in completed),
        'sol_completed_curves':sum(r['complete'] for r in sol),
        'context_slot_min':min(r['context_slot'] for r in rows),'context_slot_max':max(r['context_slot'] for r in rows),
        'started_at_utc':run['started_at_utc'],'finished_at_utc':run['finished_at_utc'],
        'historical_peak_reserves_supplied':False,'historical_completion_reserves_supplied':False,
        'production_liveness_history_complete':False,'prewindow_root_census_available':False,
        'historical_counterfactual_graduation_count':None,
        'status':'owner_approved_completed_baseline_and_no_completion_snapshot_accounting'}
    (OUT/'consolidation_input_audit.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8',newline='\n')
    lines=['<!-- generated by scripts/narrative/audit_consolidation_inputs.py -->',
        '# Consolidation outcome corrections and evidence gaps','',
        f"All {len(rows)} original launches now have decoded current bonding-curve snapshots; "
        f"finalized context slots {report['context_slot_min']}–{report['context_slot_max']}. "
        f"SOL quoted: {len(sol)}; non-SOL excluded from SOL arithmetic: {report['non_sol_quoted']} "
        f"({report['non_sol_quoted']/len(rows):.2%}, rather than extrapolating the earlier subset’s quote mix).",'',
        f"**Initial correction, subsequently resolved by the owner’s framing:** {len(completed)} curves "
        f"have complete=true, and {report['completed_with_zero_current_real_quote_reserves']} of "
        f"those have current real_quote_reserves=0. Among SOL quotes, {report['sol_completed_curves']} "
        'are marked complete. These zero fields are real current observations, not evidence that '
        'those coins never accumulated funding. The owner clarified that any completed member '
        'makes its narrative an existing fragmented-market success, contributing no additional '
        'graduation. The headline evaluates only groups with no completed member, using their '
        'current sums; historical peaks can make that conservative accounting count larger.', '',
        'The follow-up collector verifies canonical migration pools and re-reads each SOL text '
        'group atomically. Current pool WSOL reserve, excluding waiting protocol/creator fees '
        'and virtual boost, restores completed members’ money when measuring c across both '
        'completion classes. The original all-launch cache keeps complete flags distinct from '
        'migration verification; raw bytes are retained in both stages.', '',
        'The known stored-input limitations also persist: per-room launch-time reserve, idle and '
        'volume histories are missing for production gate replay. Current account balances do '
        'not repair them. Grace eligibility can be proved for a bounded prefix after a known '
        'in-window root, but an expired-grace target is unknown without historical activity. '
        'The true number of roots before the sample window cannot be counted from this window '
        'alone; it must remain unknown, not zero.', '',
        'The brief’s stop-and-record rule was followed, and the owner authorized finishing this '
        'corrected accounting measurement. Current reserve is a conservative historical-aggregate '
        'proxy only with grouping and cashflows held fixed; the unknown historical count need not '
        'be strictly higher. It is not a causal guarantee about a shared market. Uncompleted does '
        'not itself mean live under the production reserve/idle/volume gate. Current c measures '
        'a stock of reserve, not lifetime copy spending.']
    text='\n'.join(lines)+'\n'
    (OUT/'consolidation_input_audit.md').write_text(text,encoding='utf-8',newline='\n')
    path=ROOT/'CONSOLIDATION_VALUE.md'
    begin,end='<!-- BEGIN GENERATED OUTCOME CORRECTION -->','<!-- END GENERATED OUTCOME CORRECTION -->'
    content='\n'.join(lines[3:]).strip()
    previous=path.read_text(encoding='utf-8') if path.exists() else ''
    if begin in previous:
        before,tail=previous.split(begin,1)
        _,after=tail.split(end,1)
        doc=before+begin+'\n'+content+'\n'+end+after
    elif not previous:
        doc='\n'.join(['# Consolidation value — measurement correction', '',
             '**The historical counterfactual graduation count is unmeasured.**', '',
             begin,content,end,''])
    else:
        doc=previous
    if doc!=previous:path.write_text(doc,encoding='utf-8',newline='\n')
    print(text)


if __name__=='__main__':
    main()
