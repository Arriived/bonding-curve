"""Measure whether a low-detail filter rescues image-assisted routing precision.

Entropy is Shannon entropy in bits on the same 32x32 grayscale input used for pHash.
The cutoff is applied to BOTH compared images. No entropy cutoff is adopted silently.
Usage: python3 scripts/narrative/calibrate_image_entropy.py
"""
import csv
import json

import numpy as np
from PIL import Image
import calibrate_text as T
from calibrate_images import replay, ROOT, OUT, SCRIPTS
from calibration_common import ground_truth, verify_image_labels
from fetch_token_images import CACHE
from phash import flatten_alpha


def entropy(path):
    with Image.open(path) as image:
        gray=flatten_alpha(image).convert('L').resize((32,32),Image.Resampling.LANCZOS)
        counts=np.bincount(np.asarray(gray).ravel(),minlength=256)
    p=counts[counts>0]/counts.sum()
    return float(-(p*np.log2(p)).sum())


def main():
    manifests=[json.loads(line) for line in (OUT/'token_images.jsonl').read_text(encoding='utf-8').splitlines()]
    by_hash={}
    for row in manifests:
        if row.get('phash') and row['image_sha256'] not in by_hash:
            by_hash[row['image_sha256']]=entropy(CACHE/row['cache_key'])
    images={row['mint']:row for row in manifests}
    verify_image_labels(images,SCRIPTS/'labels_images_assistant.csv')
    rows=T.load(OUT/'pump_launches.jsonl')
    for row in rows:
        m=images[row['mint']]
        row['phash']=m.get('phash')
        row['entropy']=by_hash.get(m.get('image_sha256'),0)
    _,_,population,_=ground_truth(rows,SCRIPTS/'labels_assistant.csv')
    probability,_,_,labels=ground_truth(rows,SCRIPTS/'labels_assistant.csv',SCRIPTS/'labels_images_assistant.csv')
    results=[]
    false_rows=[]
    for h in (0,10):
        for cutoff in (0,2,3,4,5,6,7,7.25,7.5,7.75,8):
            filtered=[{**r,'phash':r['phash'] if r['entropy']>=cutoff else None} for r in rows]
            routes,_=replay(filtered,h,h)
            correct=sum(probability(rows[r['root']],rows[r['candidate']]) for r in routes)
            assisted=[r for r in routes if r['text'] not in ('T3','T2n')]
            ac=sum(probability(rows[r['root']],rows[r['candidate']]) for r in assisted)
            unlabelled=sum(T.pair_key(rows[r['root']],rows[r['candidate']]) not in labels
                           and T.vkey(rows[r['root']])!=T.vkey(rows[r['candidate']])
                           and rows[r['root']]['uri']!=rows[r['candidate']]['uri'] for r in assisted)
            result={'hamming':h,'minimum_entropy_bits':cutoff,'eligible_launch_images':sum(bool(r['phash']) for r in filtered),
                    'routed':len(routes),'precision':correct/max(1,len(routes)),'recall':correct/population,
                    'assisted':len(assisted),'assisted_precision':ac/max(1,len(assisted)),
                    'assisted_unlabelled':unlabelled}
            results.append(result);print(result,flush=True)
            if cutoff==0:
                for route in assisted:
                    a,b=rows[route['root']],rows[route['candidate']]
                    if labels.get(T.pair_key(a,b))=='D':
                        false_rows.append({'hamming_setting':h,'root_name':a['name'],'candidate_name':b['name'],
                                           'root_entropy':a['entropy'],'candidate_entropy':b['entropy'],
                                           'matched_face_entropy': rows[route['matched_launch']]['entropy'],
                                           'matched_face':route['matched_face'],'matched_hamming':route['hamming']})
    report={'definition':'Shannon bits on 32x32 grayscale pHash input; threshold both images',
            'entropy_by_image_sha256':by_hash,'results':results,'known_false_assisted_routes':false_rows}
    (OUT/'image_entropy_calibration.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8', newline="\n")
    lines=['<!-- generated by scripts/narrative/calibrate_image_entropy.py -->','# Image-entropy filter measurement','',
           'Entropy is Shannon bits on the alpha-flattened 32x32 grayscale pHash input. '
           'Both candidate and matching face must pass the cutoff. Fixed original text vamp denominator; '
           'same assistant labels as image calibration. No threshold is enabled by this experiment.','',
           '| Hamming | minimum entropy (bits) | eligible launch images | routed | precision (est.) | recall (est.) | assisted | assisted precision (est.) | unlabelled assisted |',
           '|---|---|---|---|---|---|---|---|---|']
    for r in results:
        lines.append(f"| {r['hamming']} | {r['minimum_entropy_bits']} | {r['eligible_launch_images']} | {r['routed']} | "
                     f"{r['precision']:.2%} | {r['recall']:.2%} | {r['assisted']} | {r['assisted_precision']:.2%} | {r['assisted_unlabelled']} |")
    lines+=['','| unfiltered Hamming | known wrong root | candidate | root entropy | candidate entropy | matched-face entropy | matched door index | matched distance |',
            '|---|---|---|---|---|---|---|---|']
    for r in false_rows:
        lines.append(f"| {r['hamming_setting']} | {r['root_name']} | {r['candidate_name']} | {r['root_entropy']:.2f} | "
                     f"{r['candidate_entropy']:.2f} | {r['matched_face_entropy']:.2f} | {r['matched_face']} | {r['matched_hamming']} |")
    lines+=['','Root-image entropy is diagnostic; the runtime filter applies to the matched face, which '
            'can be a later door. Equal hashes at a later face do not establish narrative identity with '
            'the root. Image labels are in-sample assistant judgements; a labelled false pair is evidence '
            'of a concrete failure, not a population-level error guarantee.']
    baseline=json.loads((OUT/'image_calibration.json').read_text(encoding='utf-8'))['results'][0]
    narrow=next(r for r in results if r['hamming']==0 and r['minimum_entropy_bits']==7.5)
    lines+=['',f"The strict 7.5-bit filter at Hamming 0 leaves {narrow['eligible_launch_images']} eligible "
            f"launch images and {narrow['assisted']} assisted routes, with estimated assisted precision "
            f"{narrow['assisted_precision']:.2%} and {narrow['assisted_unlabelled']} unlabelled. "
            f"Combined recall is {narrow['recall']:.2%}, a {(narrow['recall']-baseline['recall'])*100:.2f} "
            f"percentage-point gain over the same text baseline; overall precision is {narrow['precision']:.2%}. "
            "This is a small, post-selection result without held-out or human validation. "
            "It motivates validation on a new sample rather than switching on the rule. "
            "The approved production choice remains shadow mode."]
    fp0=[r for r in false_rows if r['hamming_setting']==0]
    if fp0:
        lines += ['',f"Among known unfiltered Hamming-0 errors, {sum(r['matched_face']>0 for r in fp0)}/{len(fp0)} "
                  f"matched later doors. The lowest matched-face entropy is "
                  f"{min(r['matched_face_entropy'] for r in fp0):.2f} bits. "
                  "These observed failures are not explained by plain-colour images; mild entropy "
                  "cutoffs do not solve identity drift through later faces."]
    (OUT/'image_entropy_calibration.md').write_text('\n'.join(lines)+'\n',encoding='utf-8', newline="\n")


if __name__=='__main__':
    main()
