"""Re-measure edits on decoded real sample images; never use Twemoji as a fallback.
Usage: python3 scripts/narrative/real_image_robustness.py [sample_size]
"""
import json
import random
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from fetch_token_images import CACHE, OUT
from image_robustness import SEED, THRESHOLDS, transforms
from phash import flatten_alpha, phash_hex, hamming_hex


def load(row):
    with Image.open(CACHE / row['cache_key']) as image:
        return flatten_alpha(image).resize((256, 256), Image.Resampling.LANCZOS)


def main():
    by_hash = {}
    for line in (OUT/'token_images.jsonl').read_text(encoding='utf-8').splitlines():
        row=json.loads(line)
        if row.get('phash'):
            by_hash.setdefault(row['image_sha256'],row)
    rows=[by_hash[key] for key in sorted(by_hash)]
    if not rows:
        raise SystemExit('No real images; calibration stopped.')
    rng=random.Random(SEED)
    sample=rng.sample(rows,min(int(sys.argv[1]) if len(sys.argv)>1 else 400,len(rows)))
    distances={}
    for i,row in enumerate(sample):
        base=load(row);other=load(rng.choice(rows));h=phash_hex(base)
        for name,edited in transforms(base,other,rng).items():
            distances.setdefault(name,[]).append(hamming_hex(h,phash_hex(edited)))
        if (i+1)%100==0:
            print(f'real-image robustness {i+1}/{len(sample)}',flush=True)
    lines=['<!-- generated by scripts/narrative/real_image_robustness.py -->',
           '# Real-token image edit robustness','',
           f"{len(rows)} distinct downloaded image byte hashes from the original launch sample; "
           f"{len(sample)} sampled without replacement, seed {SEED}. "
           'Alpha composited on white; sources normalized to 256x256 before the edit experiment. '
           'Each positive is an actual token image against a scripted edit of itself, not a narrative label. '
           'This is robustness recall, not routing precision. No Twemoji images used.','',
           '| edit | median | p90 | maximum | '+' | '.join(f'<= {t}' for t in THRESHOLDS)+' |',
           '|---|---|---|---|'+'---|'*len(THRESHOLDS)]
    for name,ds in distances.items():
        a=np.array(ds)
        lines.append(f'| {name} | {np.median(a):g} | {np.percentile(a,90):g} | {a.max()} | '+
                     ' | '.join(f'{(a<=t).mean():.1%}' for t in THRESHOLDS)+' |')
    lines+=['','Distinct image byte hashes can still depict the same subject; their proximity is not '
            'treated as a semantic false-positive rate. Narrative precision is measured by the routing replay.']
    (OUT/'real_image_robustness.md').write_text('\n'.join(lines)+'\n',encoding='utf-8', newline="\n")
    (OUT/'real_image_robustness.json').write_text(json.dumps({'seed':SEED,'sample_sha256':
       [r['image_sha256'] for r in sample],'distances':distances},indent=2)+'\n',encoding='utf-8', newline="\n")


if __name__=='__main__':
    main()
