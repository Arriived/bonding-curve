"""Probe original-sample metadata and same-CID gateways, recording failures without substitute images.

Usage: python3 scripts/narrative/probe_image_hosts.py [--render-only]
--render-only uses recorded responses and makes no network requests.
Exits 2 when no endpoint returns metadata JSON. No threshold calibration is inferred from accessibility.
"""
import concurrent.futures
import datetime
import json
import sys
import urllib.request
import urllib.parse
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "outputs" / "narrative"


def fetch(item):
    host, url = item
    row = {"host": host, "url": url}
    try:
        request = urllib.request.Request(url, headers={"User-Agent": "bonding-curve-research/1.0"})
        with urllib.request.urlopen(request, timeout=15) as response:
            body = response.read(2_000_000)
            row.update(status=response.status, content_type=response.headers.get("content-type"),
                       bytes=len(body))
            try:
                metadata = json.loads(body)
                row["metadata_json"] = isinstance(metadata, dict)
                row["image_uri"] = metadata.get("image") if isinstance(metadata, dict) else None
            except (ValueError, UnicodeError):
                row["metadata_json"] = False
    except Exception as error:
        row["error"] = str(error)
    return row


def main():
    if '--render-only' in sys.argv:
        render(json.loads((OUT/'image_host_probe.json').read_text(encoding='utf-8')))
        return 0
    launches = [json.loads(line) for line in (OUT / "pump_launches.jsonl").read_text(encoding="utf-8").splitlines()]
    hosts = {"ipfs.io", "metadata.j7tracker.io", "pump.mypinata.cloud", "gateway.pinata.cloud",
             "meta.uxento.io", "storage.googleapis.com"}
    urls = {}
    for launch in launches:
        host = urllib.parse.urlparse(launch["uri"]).netloc
        if host in hosts:
            urls.setdefault(host, launch["uri"])
    cid = next(r["uri"].split("/ipfs/", 1)[1] for r in launches if "/ipfs/" in r["uri"])
    for host in ("dweb.link", "w3s.link", "cloudflare-ipfs.com"):
        urls[host] = f"https://{host}/ipfs/{cid}"
    with concurrent.futures.ThreadPoolExecutor(max_workers=9) as executor:
        rows = list(executor.map(fetch, urls.items()))
    usable = sum(bool(row.get("metadata_json")) for row in rows)
    report = {"checked_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
              "method": "GET original sample metadata URIs and same-CID IPFS gateways",
              "metadata_json_responses": usable, "rows": rows}
    (OUT / "image_host_probe.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n")
    render(report)
    return 0 if usable else 2


def render(report):
    rows = report['rows']
    usable = report['metadata_json_responses']
    lines = ["<!-- generated by scripts/narrative/probe_image_hosts.py -->", "# Real-image access check", "",
             f"Checked at {report['checked_at_utc']}. {usable}/{len(rows)} endpoints returned metadata JSON.", "",
             "| host | result |", "|---|---|"]
    for row in rows:
        result = row.get("error", f"HTTP {row.get('status')}; JSON={row.get('metadata_json')}")
        lines.append(f"| {row['host']} | {result} |")
    lines += ["", "Probe URLs and exact errors are in image_host_probe.json. These are offline research "
              "access observations. V1 excludes image processing entirely, including shadow work; "
              "host accessibility has no v1 launch-routing role."]
    (OUT / "image_host_probe.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))



if __name__ == "__main__":
    raise SystemExit(main())
