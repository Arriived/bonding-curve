"""Tables for choosing the pre-graduation liveness thresholds, from liveness_reads.py output.

A: share of real copies (different creator, identical identity or URI) whose target room would pass the gate at
   the moment the copy launched: the recall the gate keeps.
B: share of random launches that pass the gate at read time, for launches from the sample window and from about
   1 and 7 days earlier: how much of the namespace the gate retires.
Only SOL-quoted curves are used (liveness_quote_mints.py): a pump.fun curve quoted in another token reports its
reserves in that token's units. In A, a copy's room counts only its SOL-quoted members, for both reserve and idle
time; copies with no SOL-quoted earlier member are dropped.
Usage: python3 liveness_table.py <liveness_reads.json> <liveness_quote_mints.json> <out.md>
"""
import json
import statistics
import sys
from pathlib import Path

from matcher import DEFAULTS

R_MIN_SOL = [0, 0.5, 1, 2, 3, 5, 10]
T_IDLE = [("10 min", 600), ("1 h", 3600), ("6 h", 21600), ("24 h", 86400)]


def main():
    d = json.load(open(sys.argv[1]))
    qm = json.load(open(sys.argv[2]))
    copies = {c["copy_sig"]: c for c in json.loads(
        Path(sys.argv[1]).with_name("copies.json").read_text(encoding="utf-8"))}
    SOLQ = {"11111111111111111111111111111111", "So11111111111111111111111111111111111111112"}
    is_sol = lambda m: qm["quote_mint"].get(m) in SOLQ
    A, dropped = [], 0
    for a in d["part_a_copies"]:
        reads = [r for r in a["reads"] if is_sol(r["mint"])]
        if not reads:
            dropped += 1
            continue
        times = [r["time"] for r in reads if r.get("time")]
        members = [m for m in copies[a["copy_sig"]]["members"] if is_sol(m["mint"])]
        A.append({"room_reserve": sum(r["real_sol_reserves"] for r in reads),
                  "age": a["copy_time"] - min(m["launch_time"] for m in members),
                  "room_idle": (a["copy_time"] - max(times)) if times else None})
    n = len(A)
    all_a = A[:]
    no_trade = sum(1 for a in A if a["room_idle"] is None)
    A = [a for a in A if a["room_idle"] is not None]
    L = ["<!-- generated by scripts/narrative/liveness_table.py -->",
         "**Historical raw-snapshot proxy only.** Non-trade/missing reads contain zero placeholders; "
         "their reserve/idle values do not establish full room state. These sweeps are not production "
         "measurements or rigorous full-gate recall bounds. Use recall_bounds.md for supported conditional bounds.", "",
         f"Program {d['program']}. Part A: {len(d['part_a_copies'])} copies sampled (seed {d['seed']}); {dropped} "
         f"dropped because no earlier member curve is SOL-quoted; {n} used, of which {no_trade} had no earlier "
         f"activity on a member curve and count as not live. Quote mints read at slots "
         f"{qm['context_slots'][0]:,}–{qm['context_slots'][-1]:,}.", "",
         "### A. Copies whose room would pass the gate when the copy launched (recall kept)", "",
         "| reserve >= (SOL) | " + " | ".join(f"idle <= {n}" for n, _ in T_IDLE) + " |",
         "|---|" + "---|" * len(T_IDLE)]
    for r in R_MIN_SOL:
        cells = []
        for _, t in T_IDLE:
            k = sum(1 for a in A if a["room_reserve"] >= r * 1e9 and a["room_idle"] <= t)
            cells.append(f"{k / n:.0%}")
        L.append(f"| {r} | " + " | ".join(cells) + " |")
    res = sorted(a["room_reserve"] / 1e9 for a in A)
    idle = sorted(a["room_idle"] for a in A)
    q = lambda xs, p: xs[min(len(xs) - 1, int(p * len(xs)))]
    L += ["", f"Room reserve at copy time (SOL): median {statistics.median(res):.2f}, p25 {q(res, .25):.2f}, "
          f"p75 {q(res, .75):.2f}. Room idle at copy time (s): median {statistics.median(idle):.0f}, "
          f"p75 {q(idle, .75):.0f}, p90 {q(idle, .9):.0f}."]

    now = d["part_b_read_unix"]
    L += ["", f"### B. Random launches passing the gate at read time (context slots {d['part_b_context_slots']}, "
          f"read at unix {now}; measured {d['sec_per_slot_measured']:.3f} s per slot)"]
    groups = [("launched in the sample window", d["part_b"])]
    groups += [(f"launched about {k} before the read (anchor slot {v['anchor_slot']:,})", v["rows"])
               for k, v in d["part_c"].items()]
    selected_groups = []
    for title, rows in groups:
        nonsol = sum(1 for b in rows if b["exists"] and not is_sol(b["mint"]))
        ex = [b for b in rows if b["exists"] and is_sol(b["mint"])]
        comp = [b for b in ex if b.get("complete")]
        B = [b for b in ex if not b.get("complete")]
        if not B:
            continue
        selected_groups.append((title, B))
        ages = [now - b["launch_time"] for b in B]
        L += ["", f"**{title}:** {len(rows)} launches; {nonsol} quoted in a token other than SOL, excluded; "
              f"{len(ex)} SOL-quoted curves, {len(comp)} complete "
              f"(graduated off the curve on pump.fun; excluded, since a doors room would then be gated by the pool "
              f"rule). {len(B)} remain, aged {min(ages) / 3600:.1f}–{max(ages) / 3600:.1f} h at read time.", "",
              "| reserve >= (SOL) | " + " | ".join(f"idle <= {n}" for n, _ in T_IDLE) + " |",
              "|---|" + "---|" * len(T_IDLE)]
        for r in R_MIN_SOL:
            cells = []
            for _, t in T_IDLE:
                k = sum(1 for b in B if b["real_quote_reserves"] >= r * 1e9 and b.get("last_sig_time")
                        and now - b["last_sig_time"] <= t)
                cells.append(f"{k / len(B):.1%}")
            L.append(f"| {r} | " + " | ".join(cells) + " |")
        rq = sorted(b["real_quote_reserves"] / 1e9 for b in B)
        L += ["", f"Curve reserve (SOL): median {statistics.median(rq):.3f}, p75 {q(rq, .75):.3f}, "
              f"p90 {q(rq, .9):.3f}, max {rq[-1]:.3f}."]
    reserve = DEFAULTS["live_min_reserve_lamports"]
    idle_limit = DEFAULTS["live_max_idle_seconds"]
    selected = sum(a["room_reserve"] >= reserve and a["room_idle"] <= idle_limit for a in A)
    old = sum(a["room_reserve"] >= 1_000_000_000 and a["room_idle"] <= idle_limit for a in A)
    L += ["", "### C. Reserve-and-idle baseline, before age and volume clauses", "",
          f"Defaults from matcher.py: reserve >= {reserve / 1e9:g} SOL; idle <= {idle_limit / 3600:g} h.", "",
          "| population | passing | total | share |", "|---|---|---|---|"]
    L.append(f"| sampled copies, selected floor | {selected} | {n} | {selected / n:.1%} |")
    L.append(f"| sampled copies, previous 1 SOL floor | {old} | {n} | {old / n:.1%} |")
    for title, rows in selected_groups:
        passing = sum(b["real_quote_reserves"] >= reserve and b.get("last_sig_time") is not None
                      and now - b["last_sig_time"] <= idle_limit for b in rows)
        L.append(f"| {title} | {passing} | {len(rows)} | {passing / len(rows):.1%} |")
    ages = sorted(a["age"] for a in all_a)
    young = DEFAULTS["live_new_seconds"]
    L += ["", "### D. Age-aware gate calibration", "",
          f"Recorded SOL-member age at copy time: median {statistics.median(ages):g} s; "
          f"p75 {q(ages, .75)} s; p90 {q(ages, .9)} s; p99 {q(ages, .99)} s; maximum {max(ages)} s. "
          "Quantiles use sorted[min(n-1, floor(p*n))]. Age is measured from the earliest "
          "earlier member with a recorded SOL quote; it is a proxy for room creation.", "",
          "| T_new | young copies under the creation proxy | legacy raw reserve+idle+age count |",
          "|---|---|---|"]
    baseline = lambda a: a["room_idle"] is not None and a["room_reserve"] >= reserve and a["room_idle"] <= idle_limit
    for seconds in (0, 60, 300, 600, 900, 1800, 3600, 5400, 7200, 21600):
        k = sum(a["age"] < seconds for a in all_a)
        passes = sum(a["age"] < seconds or baseline(a) for a in all_a)
        L.append(f"| {seconds / 3600:g} h | {k}/{n} | {passes}/{n} ({passes / n:.1%}) |")
    grace_count = sum(a["age"] < young for a in all_a)
    old_grace_count = sum(a["age"] < 7200 for a in all_a)
    L += ["", f"Selected T_new = {young / 3600:g} h: covers {grace_count}/{n} sampled targets "
          f"({grace_count/n:.1%}), costing {100*(old_grace_count-grace_count)/n:.2f} percentage points "
          "of grace coverage versus the previous 2 h. It lies inside the observed collection window "
          "and retains more than nine in ten sampled targets. Full-copy-cohort counts and age "
          "percentiles are in age_window_calibration.md. Long-run recall remains unmeasured.", "",
          "| population at read time | young | legacy raw age+reserve+idle count |",
          "|---|---|---|"]
    for title, rows in selected_groups:
        k = sum(now - b["launch_time"] < young for b in rows)
        passes = sum(now - b["launch_time"] < young or (
            b["real_quote_reserves"] >= reserve and b.get("last_sig_time") is not None
            and now - b["last_sig_time"] <= idle_limit) for b in rows)
        L.append(f"| {title} | {k}/{len(rows)} | {passes}/{len(rows)} |")
    L += ["", "Do not multiply these legacy snapshot counts by text recall. Production end-to-end "
          "recall and the true grace routing cost remain unmeasured. The supported fixed-target curve-sum "
          "proxy bounds, with and without volume, are generated separately in recall_bounds.md; "
          "non-trade/missing zero placeholders remain unknown there."]
    Path(sys.argv[3]).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
