"""Age coverage for the full certain-copy cohort and the historical liveness subset.

Uses the existing launch window only, with the original identical-identity/URI
copy definition. No RPC calls, volume assumptions, or new narrative labels.
Usage: python3 scripts/narrative/age_window_calibration.py
"""
import json
import statistics

import calibrate_text as T
from audit_liveness_brief import OUT, load_samples
from matcher import DEFAULTS

PREVIOUS_GRACE_SECONDS = 7200
WINDOWS = (900, 1800, 3600, PREVIOUS_GRACE_SECONDS)


def duration(seconds):
    hours = int(seconds // 3600)
    minutes = int(seconds % 3600 // 60)
    remainder = seconds % 60
    return ' '.join(([f'{hours}h'] if hours else []) +
                    ([f'{minutes}m'] if minutes else []) + [f'{remainder:g}s'])


def cohort(ages):
    ages = sorted(ages)
    n = len(ages)
    percentiles = {'p50': statistics.median(ages)}
    percentiles.update({f'p{int(p*100)}': ages[min(n-1, int(p*n))] for p in (.75, .9, .99)})
    windows = [{'seconds': t, 'copies': sum(a < t for a in ages),
                'fraction': sum(a < t for a in ages) / n,
                'inclusive_copies': sum(a <= t for a in ages),
                'inclusive_fraction': sum(a <= t for a in ages) / n,
                'exactly_at_boundary': sum(a == t for a in ages)} for t in WINDOWS]
    current = sum(a < DEFAULTS['live_new_seconds'] for a in ages)
    previous = sum(a < PREVIOUS_GRACE_SECONDS for a in ages)
    return {'n': n, 'percentiles_seconds': percentiles, 'windows': windows,
            'current_grace_copies': current, 'previous_grace_copies': previous,
            'grace_coverage_loss_pp': 100 * (previous-current) / n}


def main():
    launches = T.load(OUT/'pump_launches.jsonl')
    first_identity, first_uri, all_ages = {}, {}, []
    for row in launches:
        key = T.vkey(row)
        earlier = [t for t in (first_identity.get(key), first_uri.get(row['uri'])) if t is not None]
        if earlier:
            all_ages.append(row['block_time'] - min(earlier))
        first_identity[key] = min(first_identity.get(key, row['block_time']), row['block_time'])
        first_uri[row['uri']] = min(first_uri.get(row['uri'], row['block_time']), row['block_time'])
    copies = json.loads((OUT/'copies.json').read_text(encoding='utf-8'))
    different_creator = [c['copy_time'] - min(m['launch_time'] for m in c['members']) for c in copies]
    cohorts = {'All certain copies': cohort(all_ages),
               'Different-creator certain copies': cohort(different_creator),
               'SOL liveness calibration subset': cohort([r['age'] for r in load_samples()])}
    t0, t1 = min(r['block_time'] for r in launches), max(r['block_time'] for r in launches)
    result = {'sample_seconds': t1-t0, 'sample_slots': [min(r['slot'] for r in launches), max(r['slot'] for r in launches)],
              'selected_grace_seconds': DEFAULTS['live_new_seconds'],
              'previous_grace_seconds': PREVIOUS_GRACE_SECONDS, 'cohorts': cohorts}
    (OUT/'age_window_calibration.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8', newline='\n')
    lines = ['<!-- generated by scripts/narrative/age_window_calibration.py -->', '# Target-room age distribution', '',
             f"Existing sample: {len(launches):,} launches across {(t1-t0)/3600:.2f} h "
             f"({duration(t1-t0)}), slots {result['sample_slots'][0]:,}–{result['sample_slots'][1]:,}.", '',
             '| copy cohort | n | age < 15 min | age < 30 min | age < 1 h |', '|---|---|---|---|---|']
    for name, c in cohorts.items():
        cells = [f"{w['copies']}/{c['n']} ({w['fraction']:.1%})" for w in c['windows'][:3]]
        lines.append(f"| {name} | {c['n']} | " + ' | '.join(cells) + ' |')
    for window in cohorts['All certain copies']['windows'][:3]:
        if window['exactly_at_boundary']:
            lines += ['', f"The gate uses strict <. In the full cohort, {window['exactly_at_boundary']} "
                      f"copy is exactly {window['seconds']/60:g} min old; inclusive <= coverage would be "
                      f"{window['inclusive_copies']}/{cohorts['All certain copies']['n']} "
                      f"({window['inclusive_fraction']:.1%})."]
    lines += ['', '| copy cohort | p50 | p75 | p90 | p99 |', '|---|---|---|---|---|']
    for name, c in cohorts.items():
        lines.append(f'| {name} | ' + ' | '.join(duration(v) for v in c['percentiles_seconds'].values()) + ' |')
    lines += ['', '| copy cohort | selected grace coverage | loss versus previous 2 h (percentage points) |',
              '|---|---|---|']
    for name, c in cohorts.items():
        lines.append(f"| {name} | {c['current_grace_copies']}/{c['n']} ({c['current_grace_copies']/c['n']:.1%}) | "
                     f"{c['grace_coverage_loss_pp']:.2f} |")
    lines += ['', f"Choose T_new = {DEFAULTS['live_new_seconds']/3600:g} h. It lies inside the observed window "
              'and covers more than nine in ten copies in each cohort; the shorter half-hour option covers '
              'about four in five. This trades some observed grace coverage for a shorter poisoning window, '
              'rather than choosing a grace longer than the entire sample to retain every observed copy.', '',
              'All-certain-copy and different-creator ages use the earliest earlier identity/URI-matching '
              'launch, regardless of quote currency. The SOL subset uses the earlier recorded SOL-quoted '
              'members, matching the original gate calibration. Copy identity and ordering are exactly '
              'the text calibration rules. p50 is the sample median; other quantiles use '
              'sorted[min(n-1, floor(p*n))]. The runtime age clause is strict (<); boundary counts are '
              'recorded in the JSON.', '',
              'Grace coverage is not full routing recall: older funded/active rooms can pass the mature '
              'branch. The SOL reserve/idle data bound that branch in liveness_table.md. Full-cohort '
              'mature-room histories and historical trailing volume are unavailable. Room creation is '
              'an earliest-observed-member proxy; pre-window ancestors are unobserved, so this short '
              'sample cannot establish long-run recall.']
    (OUT/'age_window_calibration.md').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
