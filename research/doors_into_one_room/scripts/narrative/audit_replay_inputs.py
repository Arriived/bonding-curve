"""Audit whether the stored launch sample supplies the state required for an end-to-end replay.

No RPC reads and no missing state filled with synthetic values.
Usage: python3 scripts/narrative/audit_replay_inputs.py
"""
import json

from audit_liveness_brief import OUT, ROOT


def main():
    launches = [json.loads(line) for line in (OUT/'pump_launches.jsonl').read_text(encoding='utf-8').splitlines()]
    historical = json.loads((OUT/'liveness_reads.json').read_text(encoding='utf-8'))
    snapshots = historical['part_a_copies']
    reads = [read for copy in snapshots for read in copy['reads']]
    launch_fields = sorted(set().union(*(row.keys() for row in launches)))
    required_fields = ['reserve', 'last_trade_at', 'liveness_buckets', 'status', 'pool']
    inventory = {
        'launches': len(launches), 'launch_fields': launch_fields,
        'launch_rows_with_any_room_state_field': sum(any(key in row for key in required_fields) for row in launches),
        'historical_copy_snapshots': len(snapshots), 'historical_member_reads': len(reads),
        'confirmed_trade_member_reads': sum(read.get('is_trade') is True for read in reads),
        'non_trade_member_reads': sum(read.get('is_trade') is False for read in reads),
        'member_reads_without_signature': sum(not read.get('sig') for read in reads),
        'current_snapshot_rows': len(historical['part_b']),
        'current_snapshot_unix': historical['part_b_read_unix'],
        'last_launch_unix': max(row['block_time'] for row in launches),
        'post_window_snapshot_delay_seconds': historical['part_b_read_unix'] - max(row['block_time'] for row in launches),
        'complete_trade_event_time_series_supplied': False,
        'measurement_status': 'insufficient_for_full_production_state_replay',
    }
    (OUT/'replay_input_audit.json').write_text(json.dumps(inventory, indent=2)+'\n', encoding='utf-8', newline='\n')
    lines = ['<!-- generated by scripts/narrative/audit_replay_inputs.py -->',
             '# Correction: the stored sample does not supply full replay state', '',
             '| supplied input | observed coverage |', '|---|---|',
             f"| launch records | {inventory['launches']}; metadata, creator, slot, signature and block time only |",
             f"| launch records with room reserve, last-trade, volume-bucket, status or pool state | {inventory['launch_rows_with_any_room_state_field']} |",
             f"| copy-time historical snapshots | {inventory['historical_copy_snapshots']} sampled copies |",
             f"| historical member-curve reads | {inventory['historical_member_reads']}; {inventory['confirmed_trade_member_reads']} confirmed trades, "
             f"{inventory['non_trade_member_reads']} non-trade signatures, {inventory['member_reads_without_signature']} without a signature |",
             f"| population account snapshots | {inventory['current_snapshot_rows']}, read "
             f"{inventory['post_window_snapshot_delay_seconds']} seconds after the last sampled launch |", '',
             'The launch window reaches beyond the grace period, but its duration does not supply '
             'the missing reserve/last-trade histories, complete trade-volume events, or graduated-pool '
             'checkpoint history. The sampled historical reads are isolated snapshots, not a state '
             'stream for every room and decision. Post-window account snapshots cannot be used as '
             'historical state at launch time.', '',
             'The earlier full-sample text/image replays explicitly treated every room as live. '
             'Their zero reserve placeholders are not observations. Turning off the volume floor '
             'alone cannot turn those runs into a measured full-gate replay. The room/door market '
             'also differs from the observed independent pump curves: aggregating their trade flows '
             'would require an explicitly specified proxy, not a claim of observed production room state.', '',
             'Consequently neither a measured full-gate precision/recall pair nor the full-sample '
             'routing-recall loss/recovery count for grace shortening can be obtained from these '
             'stored inputs alone. The existing age coverage and isolated gate-proxy measurements '
             'remain distinct quantities. Additional historical observations for the same launches '
             'would not be a new launch sample, but any pump-to-room mapping must be disclosed.', '',
             'The earlier headline retained an obsolete claim of full sampled gate retention '
             'from the earlier grace setting. This revision replaces the headline with the explicit '
             'unmeasured status and separates conditional proxy bounds from production claims.', '',
             'The owner acknowledged this conflict and authorized reporting the gaps and available '
             'bounds, while completing text-only v1 and the label-dependency notes. No production '
             'precision/recall pair is substituted with an all-live benchmark or a proxy point estimate.']
    report = '\n'.join(lines)+'\n'
    (OUT/'replay_input_audit.md').write_text(report, encoding='utf-8', newline='\n')
    doc_path = ROOT/'NARRATIVE_DETECTION.md'
    document = doc_path.read_text(encoding='utf-8')
    start, end = '<!-- BEGIN GENERATED REPLAY CORRECTION -->', '<!-- END GENERATED REPLAY CORRECTION -->'
    block = '\n'.join(line for line in report.splitlines() if not line.startswith('# '))
    if start in document:
        before, tail = document.split(start, 1)
        _, after = tail.split(end, 1)
        document = before+start+'\n'+block+'\n'+end+after
    else:
        anchor = '## Current revision corrections\n'
        document = document.replace(anchor, anchor+'\n'+start+'\n'+block+'\n'+end+'\n', 1)
    doc_path.write_text(document, encoding='utf-8', newline='\n')
    print(report)


if __name__ == '__main__':
    main()
