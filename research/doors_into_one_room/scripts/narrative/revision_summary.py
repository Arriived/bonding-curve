"""Produce a short review summary from the regenerated evidence; no hand-edited figures."""
import json
import statistics
import unittest

from audit_liveness_brief import load_samples, ROOT, OUT
from matcher import DEFAULTS as D
from gate_costs import ROOM_RENT, SLUGLOCK_RENT, SOL, FEE, DOOR_SHARE
import test_liveness


def main():
    age=load_samples()
    images=json.loads((OUT/'image_calibration.json').read_text(encoding='utf-8'))
    entropy=json.loads((OUT/'image_entropy_calibration.json').read_text(encoding='utf-8'))
    fetch=json.loads((OUT/'image_fetch_summary.json').read_text(encoding='utf-8'))
    curve=json.loads((ROOT/'outputs/curve_quantities.json').read_text(encoding='utf-8'))
    ages=json.loads((OUT/'age_window_calibration.json').read_text(encoding='utf-8'))['cohorts']
    base=images['results'][0]
    h0=next(r for r in images['results'] if r['strong']==0)
    narrow=next(r for r in entropy['results'] if r['hamming']==0 and r['minimum_entropy_bits']==7.5)
    t=D['live_new_seconds']; daily=500*86400/t
    tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_liveness.LivenessTests).countTestCases()
    examples=len(list((ROOT/'scripts/narrative/examples').glob('*.json')))
    lines=['<!-- generated by scripts/narrative/revision_summary.py -->','# Liveness revision summary','',
           f"- Gate: new-room grace {t/3600:g} h; mature reserve {D['live_min_reserve_lamports']/SOL:g} SOL, "
           f"idle <= {D['live_max_idle_seconds']/3600:g} h, trailing gross volume "
           f"{D['live_min_volume_lamports']/SOL:g} SOL per day. Slug release uses its exact complement in every status.",
           f"- Corrected age: median {statistics.median(r['age'] for r in age):g} seconds, not the "
           f"{statistics.median(r['idle'] for r in age if r['idle'] is not None):g}-second idle proxy. "
           f"The chosen grace covers {sum(r['age']<t for r in age)}/{len(age)} sampled targets; "
           'without age the full volume-aware gate has bounds because historical volume was not collected.',
           f"- Across all {ages['All certain copies']['n']} certain copies, grace covers "
           f"{ages['All certain copies']['current_grace_copies']/ages['All certain copies']['n']:.1%}; "
           f"loss versus 2 h is {ages['All certain copies']['grace_coverage_loss_pp']:.2f} percentage points. "
           f"The SOL subset loses {ages['SOL liveness calibration subset']['grace_coverage_loss_pp']:.2f} points. "
           'These are grace-coverage comparisons, not a measured full-cohort routing-recall loss.',
           f"- At verified rent, repeatedly recreating 500 unfunded identities costs {daily*ROOM_RENT/SOL:.6f} "
           f"SOL/day with recreated locks, or {daily*(ROOM_RENT-SLUGLOCK_RENT)/SOL:.6f} recurring rent "
           'with atomic lock reuse (plus initial lock rent). '
           'The cost sweep supports retaining the measured grace window.',
           f"- Corrected mature wash-cost floor: {D['live_min_volume_lamports']*FEE*(1-DOOR_SHARE)/SOL:.3f} "
           'SOL per room/day before transaction fees; gross volume counts both trade legs.',
           f"- Real images decoded for {fetch['launches_with_phash']}/{fetch['launches']} launches. "
           f"In the all-live benchmark, Hamming-0 recall is {h0['recall']:.2%} versus {base['recall']:.2%} text-only "
           f"(gain {(h0['recall']-base['recall'])*100:.2f} points), but precision "
           f"{h0['precision']:.2%} versus {base['precision']:.2%}. Owner-approved shadow mode remains.",
           f"- Entropy >= 7.5 bits leaves {narrow['assisted']} assisted routes and "
           f"{(narrow['recall']-base['recall'])*100:.2f} points of recall gain in-sample. "
           'This small post-selection result needs independent/human validation.',
           '- Real-image edits and the imagehash reference comparison replace the Twemoji calibration. '
           'All new narrative labels are assistant judgements, not human labels.',
           '- Both launch instructions require the matcher signature; identity/SlugLock is derived from '
           'door-0 metadata. Account variants and packet margins include distinct lock holders and pools.',
           f"- Verified rent rate is in rent_correction.md with raw RPC values and slot brackets. "
           f"Current default trigger {curve['trigger']:,} lamports; seed {curve['seed']:,} base units. "
           'Existing rooms keep their Config snapshot and graduate from their own sold state.',
           '- Additional fixes: conservative activity history prevents stale counter revival; '
           'shadow images no longer affect ties; matched-face storage uses the full door-index width.',
           f'- Validation entry point: run_revision.py; {tests} gate regression cases and {examples} worked examples, '
           'plus exact curve/snapshot assertions and reference-hash checks. No on-chain program is built by this research revision.']
    (OUT/'revision_summary.md').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print('\n'.join(lines))


if __name__=='__main__':
    main()
