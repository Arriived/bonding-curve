"""Generate the text-only v1 and recall-evidence summary from checked-in reports."""
import json
import unittest

from audit_liveness_brief import ROOT, OUT
from matcher import DEFAULTS as D
import test_liveness
import test_recall_evidence
import test_social
import test_consensus
import test_consolidation


def main():
    bounds=json.loads((OUT/'recall_bounds.json').read_text(encoding='utf-8'))
    labels=json.loads((OUT/'label_dependency.json').read_text(encoding='utf-8'))
    social=json.loads((OUT/'social_calibration.json').read_text(encoding='utf-8'))
    consensus=json.loads((OUT/'consensus_calibration.json').read_text(encoding='utf-8'))
    consolidation=json.loads((OUT/'consolidation_value.json').read_text(encoding='utf-8'))
    conditional=next(row for row in bounds['bounds'] if row['variant']=='with_volume')
    cur=conditional['one_hour'];n=bounds['n']
    gate_tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_liveness.LivenessTests).countTestCases()
    evidence_tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_recall_evidence.RecallEvidenceTests).countTestCases()
    social_tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_social.SocialTests).countTestCases()
    consensus_tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_consensus.ConsensusTests).countTestCases()
    consolidation_tests=unittest.defaultTestLoader.loadTestsFromTestCase(test_consolidation.ConsolidationTests).countTestCases()
    examples=len(list((ROOT/'scripts/narrative/examples').glob('*.json')))
    lines=['<!-- generated by scripts/narrative/revision_summary.py -->','# Text-only v1 and recall-evidence summary','',
           '- V1 is text-only: folded identity or folded name equality plus the shared liveness gate. '
           'It performs no image fetching, hashing, comparison, shadow computation or image tie-breaking. '
           'Legacy flags cannot re-enable image-assisted, symbol-only or fuzzy routing.',
           '- Production-equivalent end-to-end precision/recall and the true routing-recall cost of grace '
           'shortening remain unmeasured. The stored metadata sample lacks ordered per-room reserve, '
           'idle, volume, routing/status and graduated-pool checkpoint histories. The owner authorized '
           'reporting this gap and available bounds instead of fabricating a replay.',
           f"- Fixed-target pre-graduation curve-sum proxy only: {bounds['young']}/{n} targets are within "
           f"grace; {bounds['older']} are outside. Retention is bounded at {cur['pass_lower']}/{n}–"
           f"{cur['pass_upper']}/{n} ({cur['pass_lower']/n:.2%}–{cur['pass_upper']/n:.2%}), both with and without volume. "
           'These are conditional subset bounds, not full-cohort production bounds.',
           f"- In that proxy, older-target recovery is {conditional['outside_grace_recoveries_lower']}–"
           f"{conditional['outside_grace_recoveries_upper']}; lost targets are "
           f"{conditional['one_hour_loss_copies_lower']}–{conditional['one_hour_loss_copies_upper']}. "
           f"The 1 h versus 2 h retention-loss bound is {conditional['one_hour_loss_pp_lower']:.2f}–"
           f"{conditional['one_hour_loss_pp_upper']:.2f} points. No true production grace-cost point is claimed.",
           f"- Conditional all-live metadata benchmark: {labels['routes']} routes and {labels['new_rooms']} "
           f"new rooms. Semantic precision/recall estimates {labels['semantic_precision_estimate']:.2%} / "
           f"{labels['semantic_recall_estimate']:.2%} depend on assistant labels and their legacy definitions; "
           'they are not the shipped full-gate measurement.',
           f"- Independent nonempty-URI cohort: {labels['nonempty_uri_copy_denominator']} cases. "
           f"Strict URI-to-root recovery is {labels['root_same_uri_successes']}/"
           f"{labels['nonempty_uri_copy_denominator']}; room containment and semantic correctness are "
           'reported separately. The old URI-recall numerator used labels, and missing URI strings '
           'were incorrectly grouped as copied metadata in the legacy denominator.',
           '- Image scorer, hashes, fetching scripts and calibration outputs remain offline research. '
           'A future threshold must reach text-only precision on a held-out sample with human-checked labels. '
           'No existing assistant labels have human review.',
           f"- Settled thresholds remain: grace {D['live_new_seconds']/3600:g} h; reserve "
           f"{D['live_min_reserve_lamports']/1e9:g} SOL; idle {D['live_max_idle_seconds']/3600:g} h; "
           f"volume {D['live_min_volume_lamports']/1e9:g} SOL/day. Slug release is the exact gate complement.",
           '- Corrections recorded: incomplete replay inputs; stale full-retention headline; non-trade '
           'zero placeholders mistaken for observed reserve; label-dependent URI correctness and empty '
           'URI duplication. Bounds replace cross-population products.',
           f'- Validation entry point: run_revision.py; {gate_tests} gate/text-only regression cases, '
           f'{evidence_tests} evidence-bound cases, {social_tests} social-evidence cases, '
           f'{consensus_tests} real-input consensus cases, {consolidation_tests} consolidation cases and {examples} examples. Exact curve/snapshot checks '
           'remain in the regeneration pipeline. No on-chain program is built by this research revision.']
    lines += ['', '## Social-link audit', '',
        f"- Cached JSON coverage: {social['available_metadata_launches']}/{social['launches']} launches. "
        'Original JSON bytes, hashes and fetch provenance are checked in for offline reproduction. '
        'Missing, empty, null, malformed and placeholder social values never form copy clusters.',
        '- Recommendation: reject all social tiers for v1. No nonredundant cap demonstrates the '
        'text precision operating point from the available independent evidence. V1, its tie order '
        'and worked examples remain unchanged; this is not a new image or shadow path.']
    for tier in ('x_post','x_account','website_domain','telegram'):
        x=next(x for x in social['experiments'] if x['tier']==tier and x['cap_text_groups'] is None and x['combined_with_text'])
        cap=social['tier_decisions'][tier]['comparison_cap']
        capped=next(x for x in social['experiments'] if x['tier']==tier and x['cap_text_groups']==cap and x['combined_with_text'])
        low,high=x['conditional_precision_bound']
        lines.append(f"- {tier}: {x['incremental_routes']} additional routes uncapped; "
            f"{capped['incremental_routes']} at prefix diversity cap {cap} distinct v1 text groups per link. "
            f"Uncapped combined precision evidence bound {low:.2%}–{high:.2%}. These are conditional "
            'policy/assistant-label bounds, not measured production precision or true recall gain.')
    lines += [f"- Existing labels leave {social['unlabelled_review_pairs']}/{social['review_pairs']} "
        'distinct review pairs unlabelled across the swept policies. Social equality is never '
        'used to label its own semantic correctness; full standalone precision/recall points remain unmeasured.',
        '- Corrections: historical JSON availability does not imply v1 already fetches it; '
        'a shared post proves a common reference, not an authenticated same-narrative market; '
        'text-selected label rates cannot be silently transferred to social-only pairs. '
        'The report includes root-contamination effects, frequency sweeps, strict URI/post anchors '
        'and a review queue. See social_calibration.md for the complete result.']
    k4=next(x for x in consensus['experiments'] if x['signals']=='six_signals' and x['k']==4 and x['combined_with_text'])
    k5=next(x for x in consensus['experiments'] if x['signals']=='six_signals' and x['k']==5 and not x['combined_with_text'])
    correlations=consensus['error_correlation_estimator']
    direct=consensus['error_correlation_direct_D']
    positive=sum(x['lift'] is not None and x['lift']>1 for x in correlations)
    d_positive=sum(x['lift'] is not None and x['lift']>1 for x in direct)
    d_computable=sum(x['lift'] is not None for x in direct)
    lines += ['', '## K-of-n audit', '',
        '- Recommendation: reject k-of-n for v1. No tested setting adds estimated recall while '
        'retaining the unrounded text precision point, either with all six signals or in the '
        'image-free ablation. Images remain research only; no matcher, tie-order or example route changes.',
        f"- Text OR six-signal k=4 adds {k4['new_routes_over_text']} routes and "
        f"{k4['net_recall_change_points_estimate']:.4f} estimated recall points, but precision is "
        f"{k4['precision_estimate']:.2%}. Standalone k=5 reaches {k5['precision_estimate']:.2%} "
        f"precision at {k5['recall_estimate']:.2%} recall, adding {k5['new_routes_over_text']} routes over text.",
        f"- Weighted estimator co-errors exceed independence for {positive}/{len(correlations)} "
        f"signal pairs. The direct-D check shows positive association for {d_positive}/{d_computable} "
        'computable signal-pair correlations and lacks image-negative coverage. The evidence does '
        'not uniformly establish the broad correlation hypothesis.',
        f"- Crowded means lexical launch frequency at or above the observed p75 cutoff "
        f"{consensus['crowding']['cutoff_launch_frequency']}; "
        f"{consensus['crowding']['counts']['crowded']} launches are crowded. Six-signal standalone "
        'precision is worse there at k=2 and k=3, but not at every threshold. Full co-error and '
        'crowding tables are in consensus_calibration.md.',
        f"- The requested legacy comparison freezes expected copies at "
        f"{consensus['legacy_expected_copy_population']:.6f}, including the documented empty-URI "
        'definition bug. A separate nonempty-URI sensitivity removes that credit: denominator '
        f"{consensus['nonempty_uri_expected_copy_population']:.6f}; no policy qualifies there either. "
        'Missing features never cast votes. Scores without text-stratum or direct-label support '
        'are zero by the archived estimator, not confirmed semantic errors.',
        '- All precision/recall, co-error and crowded precision figures are conditional assistant-label '
        'estimates. Production full-gate metrics remain unmeasured. The new review queue preserves '
        'the root/candidate mint pairs needing independent judgement without inventing labels.']
    value=consolidation
    all_c=value['distributions']['all_groups_both_statuses']['weighted_mean']
    copy_c=value['distributions']['copy_clusters_both_statuses']['weighted_mean']
    lines += ['', '## Consolidation value measurement', '',
        f"- Snapshot accounting finds {value['thresholds'][0]['additional_candidates']} additional "
        f"graduation candidates at the actual spec default {value['thresholds'][0]['threshold_lamports']/1e9:.9f} SOL. "
        f"{value['completed_groups']} text groups already have a completed member and are excluded "
        f"from incremental gain; the other {value['uncompleted_groups']} are the headline population. "
        'This is a conservative current-reserve accounting result under fixed cashflows/grouping, '
        'not a claim that lifetime or causal product gain is zero.',
        f"- Reserve-weighted c across both completion classes: {copy_c:.2%} among multi-member "
        f"copy clusters, {all_c:.2%} including singletons. Pool reserves are restored for "
        f"all {value['verified_pool_members']} completed SOL members; waiting protocol/creator fees "
        'and virtual boost are excluded. These are current reserve stocks, not a lifetime spend split.',
        f"- All {value['launches']} launch curves were read; {value['sol_launches']} SOL quotes "
        f"are analysed, {value['non_sol_launches']} non-SOL quotes excluded. Per-group reserves "
        'are atomic finalized snapshots with raw account bytes and context slots preserved.',
        f"- The survival-tail estimate is alpha={value['tail_fits']['all_groups_both_statuses']['fit']['alpha_survival']:.6f} "
        f"over its selected all-group tail. The same-eligible-cohort multiplier is "
        f"{value['predictions']['eligible_same_cohort_multiplier']:.6f}x; the counted multiplier "
        'at required high thresholds is undefined because both counts are zero. Counts govern '
        'the result; selected-tail fits do not establish a universal power law.',
        '- Corrections recorded: completed zero curve reserves are baseline success outcomes, '
        'not failures; pool money must enter weighted c; raw vault balances contain waiting fees; '
        'uncompleted does not imply gate-live; and a conservative historical count need not be '
        'strictly higher. Production launch-time gate histories and the true pre-window-root '
        'truncation count remain unavailable. See CONSOLIDATION_VALUE.md and consolidation_value.json.']
    (OUT/'revision_summary.md').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print('\n'.join(lines))


if __name__=='__main__':
    main()
