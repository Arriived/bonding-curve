"""Create the before-transactions protocol and fixed real-data cohort."""
import argparse
import datetime
import hashlib
import json

import calibrate_text as T
from audit_liveness_brief import OUT,ROOT
from liveness_reads import bonding_curve
from collect_consolidation_balances import pool_addresses

PATH=OUT/'peak_preregistration.json'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--weight',choices=['pending','gross_inflow','peak_reserve'],default='pending')
    args=parser.parse_args()
    if PATH.exists():
        old=json.loads(PATH.read_text(encoding='utf-8'))
        if old['primary_c_weighting']!='pending' and args.weight not in {'pending',old['primary_c_weighting']}:
            raise SystemExit('STOP: the primary weighting is already locked; do not recut after outcomes.')
        value=old
        if args.weight!='pending':
            value['primary_c_weighting']=args.weight
            value.setdefault('locked_at_utc',datetime.datetime.now(datetime.timezone.utc).isoformat())
    else:
        source=OUT/'consolidation_value.json'
        stock=json.loads(source.read_text(encoding='utf-8'))
        launches={r['mint']:r for r in T.load(OUT/'pump_launches.jsonl')}
        groups=[]
        for g in stock['groups_data']:
            if g['member_count']<2:continue
            members=[]
            for m in g['members']:
                launch=launches[m['mint']]
                pool,vault=pool_addresses(m['mint'])
                members.append({'mint':m['mint'],'curve':bonding_curve(m['mint']),
                    'launch_signature':launch['signature'],'launch_slot':launch['slot'],'launch_time':launch['block_time'],
                    'completed':m['complete'],'pool':pool if m['complete'] else None,
                    'quote_vault':vault if m['complete'] else None,
                    'stock_reserve_lamports':m['real_sol_reserve_lamports']})
            groups.append({'root_mint':g['root_mint'],'member_count':g['member_count'],
                'completed':g['any_completed'],'root_launch_time':g['root_launch_time'],
                'cutoff_slot':g['context_slot'],'cutoff_utc':g['received_at_utc'],'members':members})
        groups.sort(key=lambda g:(g['member_count'],g['root_mint']))
        value={'created_at_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),
            'status':'pre-transaction protocol; weighting clarification pending',
            'primary_c_weighting':args.weight,'c_rejection_threshold':.25,
            'near_zero_additional_count_max':2,
            'near_zero_definition':'zero to two additional narratives, less than one percent of the full fixed copy-cluster cohort',
            'decision':'Either c below 25% or full-cohort additional peak-pooled count <=2 rejects; incomplete bounds that cross the rule are inconclusive.',
            'largest_member_definition':'largest cumulative gross buy inflow within each cluster; ties lowest mint',
            'weighting_variants':'pooled gross-inflow ratio, peak-pooled-reserve weighted mean, snapshot-reserve weighted mean; primary pending clarification',
            'time_horizon':'launch through each group atomic snapshot cutoff, matching the 10.18% stock comparison',
            'near_zero_endpoint_excludes_completed':True,
            'sampling_order':'ascending member count, then root mint, fixed before transaction outcomes',
            'full_transaction_collection_budget_seconds':3600,
            'signature_census_budget_seconds':1800,
            'funded_cut_usd':10000,'price_source':stock['sources']['sol_usd'],
            'trigger_lamports':stock['thresholds'][0]['threshold_lamports'],
            'cohort_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
            'groups':groups,'prewindow_root_census':'unavailable: no pre-window mint-name catalogue; curve histories do not discover other sibling mints',
            'excluded_non_sol_launches':stock['non_sol_launches'],
            'excluded_sol_singletons':stock['sol_launches']-sum(len(g['members']) for g in groups)}
    if value['primary_c_weighting']!='pending':
        value['status']='locked before full transaction collection'
    PATH.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    n=len(value['groups']);members=sum(len(g['members']) for g in value['groups'])
    lines=['<!-- generated by scripts/narrative/preregister_peak_consolidation.py -->',
        '# Peak and lifetime consolidation: preregistered protocol','',
        '**Primary result, before full transaction outcomes:** the count of simultaneous '
        'peak-pooled graduations that no member reached alone. Zero or near-zero rejects the '
        '“consolidation creates runners” claim on this evidence. The secondary diagnostic, '
        'reserve-weighted lifetime c below 25%, independently rejects it. Near-zero is fixed as at most '
        f"{value['near_zero_additional_count_max']} of {n} clusters. Missing history is unknown, "
        'not a zero; a subset cannot by itself establish a full-cohort rejection unless its bounds do so.','',
        f"Fixed cohort: {n} multi-member v1-text clusters, {members} SOL-quoted members. "
        f"Exclude {value['excluded_non_sol_launches']} non-SOL launches and "
        f"{value['excluded_sol_singletons']} SOL singletons. "
        f"{sum(g['completed'] for g in value['groups'])} clusters already have a completed member "
        'and contribute no additional graduation; they remain in lifetime c.','',
        'Reconstruct the simultaneous sum in chain transaction/instruction order, not the sum '
        'of individual peaks. Migration transfers existing reserve and is not a new buyer inflow. '
        'Post-migration pool/vault history is required for a lifecycle c comparable with stock. '
        'Histories end at the cached per-group stock snapshot, so stock and flow use one horizon.','',
        f"Primary c weighting: **{value['primary_c_weighting']}**. The brief’s pooled gross-inflow "
        'ratio and a reserve-weighted mean are different estimands; this choice must be locked '
        'before fetching full transactions. All weighting variants and a fixed-stock-leader '
        'comparison will be shown; the rejection threshold will not be switched after outcomes.','',
        '## Corrections and collection limits','',
        'A first signature page is capped at 1,000 entries and is not a total activity census '
        'when full. Completion needs pagination to the known creation boundary, and successful '
        'transactions must be decoded, not inferred from signature counts. Pool and quote-vault '
        'addresses add activity absent from curve-only history.','',
        'No pre-window launch-name catalogue exists in the repo. A member’s own curve history '
        'cannot identify an earlier sibling token with the same folded text. The true truncated-root '
        'count is therefore unmeasured unless an external launch index is supplied; an invented '
        'zero is prohibited.','',
        'The median copy lag does not establish a hard maximum lag. Observed cluster counts '
        'near the window edge will be reported as risk diagnostics, not a certified upper '
        'bound on truncation. No backward catalogue extension is authorized in this run.','',
        'Collection is cached in consolidation_history.sqlite with raw compressed RPC responses '
        f"and attempt telemetry. The signature census has a {value['signature_census_budget_seconds']/60:g}-minute budget; the subsequent "
        f"full-transaction stage has a {value['full_transaction_collection_budget_seconds']/60:g}-minute budget, with whole-cluster scheduling by ascending "
        'member count then root mint. Coverage, failures, achieved rates and elapsed time will be '
        'reported. No outcome-based selection or new semantic labels are permitted.','',
        'The census collection budget was extended before full transactions, solely because '
        'measured RPC throttling made the original collection budget insufficient. The JSON '
        'records the timestamped amendment; decision thresholds and cohort are unchanged.']
    (ROOT/'PEAK_CONSOLIDATION_PREREGISTRATION.md').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps({'clusters':n,'members':members,'primary_c_weighting':value['primary_c_weighting']},indent=2))


if __name__=='__main__':main()
