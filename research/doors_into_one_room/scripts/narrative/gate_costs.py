"""What it costs to fake liveness or poison the namespace, from the spec's fee split and the matcher thresholds.

Inputs: spec fee defaults (fee 100 bps, door share 60%, pool base fee 100 bps with 80% to positions, from
PERMANENT_CURVE_SPEC.md §3, §5.3, §5.6), account rent from scripts/account_sizes.py, thresholds from
scripts/narrative/matcher.py DEFAULTS. Deterministic.

Usage: python3 gate_costs.py > outputs/narrative/gate_costs.md
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
from account_sizes import per_door_rent_lamports, rent  # noqa: E402
from matcher import DEFAULTS as D  # noqa: E402

SOL = 1e9
FEE = 0.01           # program fee, each side
DOOR_SHARE = 0.60    # returned to the trader if they own the door they trade through
POOL_FEE = 0.01      # DAMM v2 base fee (spec assumption, §5.3)
LP_SHARE = 0.80      # 1 - PROTOCOL_FEE_PERCENT (DAMM v2 constants.rs L146)
ROOM_RENT = 20_629_440 + per_door_rent_lamports()   # launching a room with door 0 (spec §1)
SLUGLOCK_RENT = rent(17)
TX_FEE = 5_000       # one signature at 5,000 lamports per signature (assumed mainnet default)
REFRESH_TRADE = 0.01 * SOL  # smallest trade size assumed for a last_trade_at refresh


def main():
    r_min = D["live_min_reserve_lamports"]
    t_idle = D["live_max_idle_seconds"]
    f_min = D["pool_min_window_lp_fee"]
    w = D["pool_window_seconds"]
    net_side = FEE * (1 - DOOR_SHARE)               # attacker owns the door: gets 60% of its own fee back
    refresh_per_day = 86_400 / t_idle
    refresh_cost = REFRESH_TRADE * net_side * 2 + 2 * TX_FEE   # buy then sell
    reserve_round_trip = r_min * net_side * 2
    pool_volume = f_min / (POOL_FEE * LP_SHARE)
    pool_cost_window = pool_volume * POOL_FEE
    pool_cost_day = pool_cost_window * 86_400 / w

    print("<!-- generated by scripts/narrative/gate_costs.py -->")
    print(f"Thresholds (matcher.py DEFAULTS): reserve >= {r_min / SOL:g} SOL and a trade within {t_idle / 3600:g} h "
          f"before graduation; LP fee >= {f_min / SOL:g} SOL per {w / 3600:g} h window after graduation.\n")
    print("| item | lamports | SOL |\n|---|---|---|")
    rows = [
        ("launch a room with door 0, rent (spec §1)", ROOM_RENT),
        ("SlugLock rent, reused as the exact-identity floor (17 bytes)", SLUGLOCK_RENT),
        ("one last_trade_at refresh: 0.01 SOL buy + sell through the attacker's own door, net of the 60% "
         "door rebate, plus two transaction fees", refresh_cost),
        (f"keeping last_trade_at fresh for a day ({refresh_per_day:g} refreshes)", refresh_cost * refresh_per_day),
        ("putting the reserve floor in and taking it out again, net fees (capital is returned if no one else "
         "trades)", reserve_round_trip),
        (f"capital that must sit in the room's reserve while it is held live", r_min),
        (f"post-graduation: pool volume needed per window to produce the LP-fee floor", pool_volume),
        ("post-graduation: cost of that volume per window (pool fee, none of it returns to the trader)",
         pool_cost_window),
        ("post-graduation: the same per day", pool_cost_day),
    ]
    for name, v in rows:
        print(f"| {name} | {v:,.0f} | {v / SOL:.6f} |")
    print("\n**Namespace poisoning with K junk rooms held live before graduation** (room rent once, plus the "
          "reserve held as capital and a day of refreshes):\n")
    print("| K rooms | rent, once (SOL) | capital locked (SOL) | refresh cost per day (SOL) |\n|---|---|---|---|")
    for k in (10, 100, 500):
        print(f"| {k} | {k * ROOM_RENT / SOL:.2f} | {k * r_min / SOL:,.0f} | "
              f"{k * refresh_cost * refresh_per_day / SOL:.4f} |")
    print("\nThe refresh trade size and the 5,000-lamport transaction fee are assumptions. Price impact is zero for "
          "a buy followed by a sell of the same amount on the curve with no trade in between.")


if __name__ == "__main__":
    main()
