"""Deterministic poisoning and wash costs from defaults, account sizes and spec fee assumptions.
Gross volume counts BOTH legs; net cost is 40 bps per gross-volume SOL, not 80 bps.
Usage: python3 gate_costs.py > outputs/narrative/gate_costs.md
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from account_sizes import per_door_rent_lamports, per_room_rent_lamports, rent
from matcher import DEFAULTS as D
from audit_liveness_brief import load_samples
SOL = 1_000_000_000
FEE = 0.01
DOOR_SHARE = 0.60
POOL_FEE = 0.01
LP_SHARE = 0.80
ROOM_RENT = per_room_rent_lamports() + per_door_rent_lamports()
SLUGLOCK_RENT = rent(17)
TX_FEE = 5_000  # assumed signature fee, not a new mainnet read


def main():
    r, t = D['live_min_reserve_lamports'], D['live_new_seconds']
    v, w, f = D['live_min_volume_lamports'], D['live_window_seconds'], D['pool_min_window_lp_fee']
    net = FEE * (1 - DOOR_SHARE)
    recreations = 86_400 / t
    daily_volume = v * 86_400 / w
    pool_volume = f / (POOL_FEE * LP_SHARE)
    print('<!-- generated by scripts/narrative/gate_costs.py -->')
    print(f'New-room grace {t / 3600:g} h; mature reserve >= {r / SOL:g} SOL, '
          f'idle <= {D["live_max_idle_seconds"] / 3600:g} h; gross trailing volume >= {v / SOL:g} SOL '
          f'per {w / 3600:g} h. Mature pool LP-fee floor {f / SOL:g} SOL per window.\n')
    print('| item | lamports | SOL |\n|---|---|---|')
    rows = [
        ('launch room and door 0, max-metadata rent', ROOM_RENT),
        ('only reclaimable rent: SlugLock, if attacker wins cleanup', SLUGLOCK_RENT),
        ('mature curve: reserve held as capital', r),
        ('mature curve: gross volume per day, both legs counted', daily_volume),
        ('mature curve: protocol fees lost per day, own-door rebate claimed', daily_volume * net),
        ('illustrative two-transaction round trip signature fees (additional)', 2 * TX_FEE),
        ('mature pool: volume per window to generate LP-fee floor', pool_volume),
        ('mature pool: pool fees lost per window (no LP ownership)', pool_volume * POOL_FEE),
    ]
    for name, amount in rows:
        print(f'| {name} | {amount:,.0f} | {amount / SOL:.6f} |')
    print('\n**Namespace poisoning by repeated young-room creation** (unfunded rent-only defacement):\n')
    print('| K identities | rooms created per day | rent/day if each lock recreated (SOL) | steady-state rent/day reusing the lock (SOL) |\n|---|---|---|---|')
    for k in (10, 100, 500):
        print(f'| {k} | {k * recreations:g} | {k * recreations * ROOM_RENT / SOL:.6f} | '
              f'{k * recreations * (ROOM_RENT - SLUGLOCK_RENT) / SOL:.6f} |')
    print('\n**Namespace poisoning by mature rooms held live**:\n')
    print('| K rooms | rent once (SOL) | reserve capital (SOL) | protocol fees lost per day at volume floor (SOL) |\n|---|---|---|---|')
    for k in (10, 100, 500):
        print(f'| {k} | {k * ROOM_RENT / SOL:.6f} | {k * r / SOL:g} | {k * daily_volume * net / SOL:.6f} |')
    ages=[row['age'] for row in load_samples()]
    print('\n**Grace-window sensitivity at the verified rent**:\n')
    print('| grace (h) | copies covered by grace | rent/day for 500 identities with new locks (SOL) | recurring rent/day reusing locks (SOL) |\n|---|---|---|---|')
    for seconds in (900,1800,3600,5400,7200,21600):
        count=sum(age<seconds for age in ages)
        print(f'| {seconds/3600:g} | {count}/{len(ages)} | '
              f'{500*86400/seconds*ROOM_RENT/SOL:.6f} | '
              f'{500*86400/seconds*(ROOM_RENT-SLUGLOCK_RENT)/SOL:.6f} |')
    count=sum(age<t for age in ages)
    previous=sum(age<7200 for age in ages)
    print(f'\nChoose {t/3600:g} h instead of the previous 2 h: grace covers {count}/{len(ages)} '
          f'({count/len(ages):.1%}) of the SOL calibration targets, costing '
          f'{100*(previous-count)/len(ages):.2f} percentage points of grace coverage. '
          'The window is inside the observed sample and retains more than nine in ten targets. '
          'Halving grace doubles the continuous unfunded-recreation rent rate; mature-room '
          'wash costs are unchanged. Small targeted squats remain affordable; this is not an economic guarantee.')
    print('\nNo founder share exists. Merely owning door 0 earns nothing; later launches use their own doors. '
          'The rent-only attacker controls the room token name and image: defacement. '
          'Wash costs assume ownership of the trading door and its fee rebate; exclude transaction fees unless shown, '
          'integer rounding, capital opportunity cost and third-party trading. The attacker does not own the protocol LP. '
          'Atomic takeover reuses the same SlugLock: the steady-state recurring creation cost excludes its '
          'rent, which is paid once per identity. Closing and reclaiming a lock before recreating it has '
          'the same net rent if the attacker wins cleanup, with extra transaction work. '
          'One registration stops working after grace; recurring rent or volume fees can sustain poisoning. '
          'Hourly trailing lower bounds may require more volume than this optimistic attack-cost floor. '
          'Signature fees and pool fee configuration are assumptions, not current on-chain readings.')


if __name__ == '__main__':
    main()
