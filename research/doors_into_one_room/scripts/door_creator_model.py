"""What a door creator and a room founder earn, with terminal substitution on (Ruling 1).

Verified inputs:
  * doors fee defaults: PERMANENT_CURVE_SPEC.md (100 bps trade fee; 30% door creator,
    10% founder, 20% reserve, 40% protocol; door fee 0.5 SOL split 50/10/40; rent per
    door 9,166,320 lamports).
  * pump.fun creator fees, read on-chain at slot 463,695,548 from the pump fees program
    (pfeeUxB6jkeY1Hxd7CsFCAjcbHA9rWtchMGdZ6VojVZ). FeeConfig PDA ["fee_config", program]:
      bonding curve (6EF8rr...F6P) -> 8Wf5TiAheLUqBrKXeYg2JtAFFMWtKdG2BSFgqUcPVwTt:
          creator 30 bps, protocol 95 bps, flat
      PumpSwap canonical pools (pAMMBay6...EXA) -> 5PHirr8joyTMp9JMm6nW7hNDVyEYdkzDqazxPD7RaTjx:
          tiers by market cap in SOL, below.
NOT verified (no public source found; run as ranges): the share of volume that goes
through trading terminals; how much volume a creator's own community generates; how
much flow picks doors uniformly; lifetime volume of pump.fun coins that do / don't run.
"""
import importlib.util
import math
import os

USD_PER_SOL = 150.0
FEE = 0.01
CREATOR = 0.30*FEE          # 0.30% of volume through the creator's door
FOUNDER = 0.10*FEE
RESERVE = 0.20*FEE
DOOR_FEE_SOL = 0.5
RENT_SOL = 9_166_320/1e9
DOOR_COST = (DOOR_FEE_SOL+RENT_SOL)*USD_PER_SOL
FOUNDER_DOOR_FEE_SOL = 0.10*DOOR_FEE_SOL
RESERVE_DOOR_FEE_SOL = 0.50*DOOR_FEE_SOL

VOLUMES = (1e6, 10e6, 50e6)
SUBSTITUTION = (("low", 0.3), ("mid", 0.6), ("high", 0.9))   # assumed range, not measured
COMMUNITY = (0.05, 0.20)    # share of room volume generated by the creator's own traders (assumed)
RHO, DOORS = 0.05, 20        # uniform-picking share of volume and number of doors (assumed)

# PumpSwap canonical-pool creator fee tiers (threshold SOL mcap, creator bps), on-chain.
PUMPSWAP_TIERS = [(0, 30), (420, 95), (1470, 90), (2460, 85), (3440, 80), (4420, 75), (9820, 70), (14740, 65),
                  (19650, 60), (24560, 55), (29470, 50), (34380, 45), (39300, 40), (44210, 35), (49120, 30),
                  (54030, 28), (58940, 25), (63860, 23), (68770, 20), (73681, 18), (78590, 15), (83500, 13),
                  (88400, 10), (93330, 8), (98240, 5)]
CURVE_CREATOR_BPS = 30


def money(x):
    s = "-" if x < 0 else ""
    a = abs(x)
    if a >= 1e6: return f"{s}${a/1e6:,.2f}M"
    if a >= 1e3: return f"{s}${a/1e3:,.1f}k"
    return f"{s}${a:,.0f}"


def door_with_traders(V, s, a):
    return CREATOR*(1-s)*(a*V + RHO*V/DOORS)


def door_without_traders(V, s):
    return CREATOR*(1-s)*RHO*V/DOORS


def pumpswap_bps(mcap_sol):
    b = PUMPSWAP_TIERS[0][1]
    for t, bps in PUMPSWAP_TIERS:
        if mcap_sol >= t:
            b = bps
    return b


def blended_pumpswap_bps(peak_mcap_usd, start_sol=420.0):
    """Average creator bps if PumpSwap volume is spread evenly in log(mcap) from 420 SOL to the peak.
    An illustration of the tier schedule, not a measured volume distribution."""
    peak = peak_mcap_usd/USD_PER_SOL
    if peak <= start_sol:
        return 30.0
    n = 2000
    tot = 0.0
    for i in range(n):
        m = math.exp(math.log(start_sol)+(math.log(peak)-math.log(start_sol))*(i+.5)/n)
        tot += pumpswap_bps(m)
    return tot/n


def c1_price():
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location("cm", os.path.join(here, "curve_model.py"))
    cm = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cm)
    return cm.CURVES[3]


def main():
    print("<!-- generated by scripts/door_creator_model.py -->")
    print(f"Assumptions (unverified, swept or stated): terminal substitution s; creator's own community = a of room "
          f"volume; uniform-picking share rho = {RHO} spread over D = {DOORS} doors; SOL = ${USD_PER_SOL:.0f}. "
          f"Door cost = 0.5 SOL fee + rent = {money(DOOR_COST)}. First-buy trading P&L excluded here (see the "
          f"price-multiple table).\n")
    print("### Non-founder door creator: fee income over the room's life, net of the door cost\n")
    print("| room volume | substitution s | door with traders, a = 5% | a = 20% | door with no traders |\n|---|---|---|---|---|")
    for V in VOLUMES:
        for label, s in SUBSTITUTION:
            cells = [money(door_with_traders(V, s, a)-DOOR_COST) for a in COMMUNITY]
            cells.append(money(door_without_traders(V, s)-DOOR_COST))
            print(f"| {money(V)} | {label} ({s:.0%}) | " + " | ".join(cells) + " |")
    print("\nBreak-even community volume (a·V) for a door to recover its cost: "
          + ", ".join(f"s = {s:.0%}: {money(DOOR_COST/(CREATOR*(1-s)))}" for _, s in SUBSTITUTION) + ".\n")
    print("### Where the substituted flow goes: one terminal's doors (fee income across all rooms it routes)\n")
    print("| room volume | s | a terminal with 50% of terminal flow earns, per room |\n|---|---|---|")
    for V in VOLUMES:
        for label, s in SUBSTITUTION:
            print(f"| {money(V)} | {label} ({s:.0%}) | {money(CREATOR*s*V*0.5)} |")
    print("\n### The same creator launching their own pump.fun coin instead\n")
    print("On pump.fun the creator fee is paid on all of the coin's volume, whichever frontend or terminal routes "
          "it; terminal share does not reduce it.\n")
    print("| creator fee schedule (on-chain) | bps |\n|---|---|")
    print(f"| bonding curve, flat | {CURVE_CREATOR_BPS} |")
    print("| PumpSwap, market cap < 420 SOL | 30 |")
    print("| PumpSwap, 420–1,470 SOL | 95 |")
    print("| PumpSwap, 9,820–14,740 SOL | 70 |")
    print("| PumpSwap, 49,120–54,030 SOL | 30 |")
    print("| PumpSwap, ≥ 98,240 SOL | 5 |")
    print("| figure given in the brief | 5 (0.05%) |\n")
    print("| own coin | lifetime volume (assumed) | creator fees at the on-chain schedule | at 0.05% (brief) |\n|---|---|---|---|")
    for v in (2e3, 10e3, 30e3):
        print(f"| doesn't run (dies on the curve) | {money(v)} | {money(v*CURVE_CREATOR_BPS/1e4)} | {money(v*5e-4)} |")
    for v, peak in ((1e6, 1e6), (10e6, 10e6), (50e6, 50e6)):
        curve_vol = min(v, 30e3)
        b = blended_pumpswap_bps(peak)
        fees = curve_vol*CURVE_CREATOR_BPS/1e4+(v-curve_vol)*b/1e4
        print(f"| runs, peak mcap {money(peak)} | {money(v)} | {money(fees)} (PumpSwap blended {b:.0f} bps) | "
              f"{money(v*5e-4)} |")
    print("\n'Blended' spreads PumpSwap volume evenly in log market cap from 420 SOL to the peak and applies the tier "
          "in force; the first $30k is assumed to trade on the curve. These volume paths are illustrations, "
          "not measurements.\n")
    print("### Same traders, two venues: door (non-founder) vs own pump.fun coin, per $1M of the creator's own "
          "community volume\n")
    print("| s | door: 0.30% × (1 − s) | own coin on the curve (30 bps) | own coin on PumpSwap at 95 / 30 / 5 bps |"
          "\n|---|---|---|---|")
    for label, s in SUBSTITUTION:
        print(f"| {label} ({s:.0%}) | {money(CREATOR*(1-s)*1e6)} | $3.0k | $9.5k / $3.0k / $500 |")
    print("\n### Room founder\n")
    print("| room volume | founder share 0.10% | door-fee share (D = 20 doors × 0.05 SOL) | "
          "reserve retirement worth to founder at h = 1% of supply | total, excl. door-0 fees and first buy |"
          "\n|---|---|---|---|---|")
    for V in VOLUMES:
        f = FOUNDER*V
        dfee = DOORS*FOUNDER_DOOR_FEE_SOL*USD_PER_SOL
        retired = RESERVE*V+DOORS*RESERVE_DOOR_FEE_SOL*USD_PER_SOL
        h = 0.01*retired
        print(f"| {money(V)} | {money(f)} | {money(dfee)} | {money(h)} | {money(f+dfee+h)} |")
    print("\nThe founder also owns door 0, so add the door-creator income above for whatever flow door 0 receives.\n")
    c = c1_price()
    print("### First buy: price multiple from entry to a later reserve level on curve C1 "
          "(marginal price; a small buy that exits at that level)\n")
    exits = (100e3, 1e6, 10e6)
    print("| entry reserve | to $100k | to $1M | to $10M |\n|---|---|---|---|")
    for e, label in ((0, "$0 (founder, floor)"), (10e3, "$10k"), (100e3, "$100k"), (1e6, "$1M")):
        pe = c.p_of_reserve(e)
        cells = [f"{c.p_of_reserve(x)/pe:,.1f}×" if x > e else "—" for x in exits]
        print(f"| {label} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
