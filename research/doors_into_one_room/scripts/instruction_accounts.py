"""Account lists per instruction, as specified in PERMANENT_CURVE_SPEC.md §3, and their counts.

Checks each list against the 64-account transaction lock limit (agave runtime/src/bank.rs:3847)
and estimates legacy-message size: 32 bytes per account key; a legacy transaction must fit in a
1,232-byte packet (signatures, header, blockhash and instruction data share that budget).
Counts include program accounts invoked. Deterministic.
"""
CURVE_DOOR = ["user", "config", "room", "reserve_vault", "fee_vault", "room_vault", "room_mint", "user_door_ata",
              "door", "door_mint", "door_vault", "door_room_vault", "token_2022_program", "system_program",
              "event_authority", "doors_program"]
CURVE_ROOM = ["user", "config", "room", "reserve_vault", "fee_vault", "room_vault", "room_mint", "user_room_ata",
              "token_2022_program", "system_program", "event_authority", "doors_program"]
POOL_EXTRA = ["damm_program", "damm_pool_authority", "damm_pool", "damm_token_a_vault", "damm_token_b_vault",
              "wsol_mint", "user_wsol_ata", "spl_token_program", "damm_event_authority", "fee_wsol"]
CONVERT = ["user", "config", "room", "fee_vault", "door_a", "door_b", "door_mint_a", "door_mint_b", "door_vault_a",
           "door_vault_b", "door_room_vault_a", "door_room_vault_b", "room_mint", "user_ata_a", "user_ata_b",
           "token_2022_program", "system_program"]
OPEN_DOOR = ["opener", "config", "room", "fee_vault", "door", "door_mint", "door_vault", "door_room_vault", "room_mint",
             "ticker_lock", "token_2022_program", "system_program", "event_authority", "doors_program"]
GRADUATE = ["cranker", "config", "room", "reserve_vault", "room_vault", "retired_vault", "room_mint", "grad_payer",
            "grad_payer_wsol_tmp", "grad_payer_room_ata", "pool_creator_pda", "position_nft_mint_pda",
            "position_nft_account", "damm_config", "damm_pool_authority", "damm_pool", "damm_position",
            "wsol_mint", "damm_token_a_vault", "damm_token_b_vault", "protocol_fee_recipient",
            "protocol_nft_ata", "damm_program", "damm_event_authority", "token_2022_program", "spl_token_program",
            "associated_token_program", "system_program", "event_authority", "doors_program", "fee_vault"]
LISTS = {
    "buy/sell, door route, curve": CURVE_DOOR,
    "buy/sell, room-token route, curve": CURVE_ROOM,
    "buy/sell, door route, pool": CURVE_DOOR+POOL_EXTRA,
    "buy/sell, room-token route, pool": CURVE_ROOM+POOL_EXTRA,
    "convert": CONVERT,
    "open_door (without first buy)": OPEN_DOOR,
    "graduate": GRADUATE,
}


def main():
    print("<!-- generated by scripts/instruction_accounts.py -->")
    print("| instruction | accounts | under 64-lock limit | account keys alone (bytes) | fits a legacy 1,232-byte "
          "packet without a lookup table? |\n|---|---|---|---|---|")
    for name, accts in LISTS.items():
        assert len(set(accts)) == len(accts), name
        n = len(accts)
        keys = 32*n
        # one signature (64) + header/blockhash/compact-array overhead (~40) + instruction data (assume <= 100)
        fits = keys+64+40+100 <= 1232
        print(f"| {name} | {n} | {'yes' if n <= 64 else 'NO'} | {keys:,} | {'yes' if fits else 'no: use a v0 transaction with an address lookup table'} |")
    print("\nThe 64-byte signature, ~40 bytes of header/blockhash/array overhead and <=100 bytes of instruction "
          "data in the packet estimate are assumptions for the check, not measurements.")


if __name__ == "__main__":
    main()
