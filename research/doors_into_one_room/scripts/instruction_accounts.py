def shortvec(n):
    return 1 if n < 128 else 2 if n < 16384 else 3


def legacy_size(keys, signatures, data_bytes, instruction_accounts):
    return (shortvec(signatures) + 64 * signatures + 3 + shortvec(keys) + 32 * keys + 32
            + 1 + 1 + shortvec(instruction_accounts) + instruction_accounts
            + shortvec(data_bytes) + data_bytes)


def main():
    print("<!-- generated by scripts/instruction_accounts.py -->")
    print("| instruction | accounts | signatures | under 64-lock limit | modelled legacy bytes | packet margin (bytes) |\n|---|---|---|---|---|---|")
    for name, accts in LISTS.items():
        assert len(set(accts)) == len(accts), name
        n = len(accts)
        assert n <= 64, name
        signatures = 2 if name.startswith(('open_door', 'create_room')) else 1
        # Anchor discriminator + three max metadata strings + buy/slippage + evidence including image digest.
        data = 8 + (4+32) + (4+10) + (4+200) + 8+8 + 2+1+4+8+32 if signatures == 2 else 8
        size = legacy_size(n, signatures, data, n)
        print(f"| {name} | {n} | {signatures} | {'yes' if n <= 64 else 'NO'} | {size} | {1232-size} |")
    grad = legacy_size(len(GRADUATE), 1, 8, len(GRADUATE))
    # Add ComputeBudget program key plus set-CU-limit (5 data bytes) and set-CU-price (9 data bytes).
    with_budget = grad + 32 + (1+1+1+5) + (1+1+1+9)
    print(f"\n`graduate`: {len(GRADUATE)} keys, one signature, 8-byte discriminator, "
          f"one instruction: {grad} bytes, {1232-grad} bytes spare. With one ComputeBudget key "
          f"and limit/price instructions: {with_budget} bytes, {1232-with_budget} spare.")
    print("\nThese are serialized-size models, not a compiled-program measurement. Each root instruction "
          "passes every listed key; aliases are deduplicated in a real message. Launches have two distinct "
          "signers and max metadata/evidence. Other instructions use an assumed 8-byte discriminator only. "
          "Optional first-buy account unions, ATA creation and extra instructions require a new packet check. "
          "Negative margins require a v0 message and lookup table (or instruction splitting where atomicity permits). "
          "Use v0/ALT for launch and graduation transactions to leave compute-budget and composition margin.")
    print("\nAccount metas (R read, W write, S signer):\n")
    print("| launch/release addition | role |\n|---|---|")
    for key, role in [('matcher_authority','R,S; mandatory for both launch instructions'),
                      ('slug_lock','R for open_door; W for create_room/release_slug'),
                      ('identity_holder_room / previous_holder_room','R; verify key/id from lock, optional only if no distinct holder'),
                      ('damm_pool / identity_holder_damm_pool / previous_holder_damm_pool','R; required for the corresponding graduated room'),
                      ('config','R; authority and the single set of liveness constants'),
                      ('room','W for trades, launch and checkpoints; R for release_slug')]:
        print(f"| {key} | {role} |")


if __name__ == "__main__":
    main()
