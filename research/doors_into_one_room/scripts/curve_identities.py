"""Exact checks for the room curve (constant product with virtual reserves, graduating into a pool).

Exact rational arithmetic (fractions.Fraction) throughout; integer lamports and base units
(6 decimals) where the program would use them. Deterministic; no market data.

Notation: S total supply, f fraction sold on the curve, R* graduation reserve, V_sol / V_tok
virtual reserves, K = V_sol * V_tok. Curve: x = V_sol + R, y = V_tok - s, x*y = K.
Pool after graduation: (R*, (1 - f) S), constant product K' = R* (1 - f) S.
"""
from fractions import Fraction as F
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from account_sizes import graduation_rent_lamports  # noqa: E402

LAMPORTS = 10**9
DEC = 10**6
S = F(10**9)
f = F(7931, 10000)
R_STAR = F(85)
V_TOK_BRIEF = F(1_073_025_606)
V_TOK_PUMP = F(1_073_000_000)


def fmt(x, n=6):
    return f"{float(x):,.{n}f}"


def junction(v_sol, v_tok, trigger="tokens"):
    """Return (s at switch, R at switch, curve price, pool price, step) for a parameter set.
    trigger='tokens': switch at s = f S (pump.fun). trigger='reserve': switch at R = R*."""
    K = v_sol*v_tok
    if trigger == "tokens":
        s = f*S
        R = K/(v_tok-s)-v_sol
    else:
        R = R_STAR
        s = v_tok-K/(v_sol+R)
    curve_p = (v_sol+R)/(v_tok-s)
    pool_p = R/(S-s)
    return s, R, curve_p, pool_p, pool_p/curve_p-1


def integer_curve(v_sol_lamports, v_tok_base):
    """Integer implementation the program uses: R(q) = floor(K/(V_tok-q)) - V_sol (lamports, base units).
    Trigger: graduation when the reserve reaches R*; q_g = largest q with R(q) <= R*."""
    K = v_sol_lamports*v_tok_base
    assert K//v_tok_base == v_sol_lamports and K % v_tok_base == 0     # R(0) = 0 exactly
    r_star = 85*LAMPORTS
    T = r_star
    q_g = v_tok_base-K//(T+v_sol_lamports+1)-1
    R = lambda q: K//(v_tok_base-q)-v_sol_lamports
    assert R(q_g) <= r_star < R(q_g+1)
    seed_tokens = 10**15-q_g
    curve_p = F(K, (v_tok_base-q_g)**2)                # marginal lamports per base unit
    pool_p = F(R(q_g), seed_tokens)
    return dict(K=K, q_g=q_g, R_qg=R(q_g), seed_tokens=seed_tokens, step=pool_p/curve_p-1,
                unspent=r_star-R(q_g))


def main():
    out = ["<!-- generated by scripts/curve_identities.py -->", ""]
    v_tok_exact = f*f*S/(2*f-1)
    v_sol_from_r = R_STAR*(1-f)/(2*f-1)
    out += ["### Identities (exact rational arithmetic)", "",
            "| identity | value | check |", "|---|---|---|",
            f"| V_tok = f²S/(2f−1) | {fmt(v_tok_exact, 4)} | brief's 1,073,025,606 is this rounded up by "
            f"{fmt(V_TOK_BRIEF-v_tok_exact, 4)} |",
            f"| V_sol = R*(2f−1)/(1−f) (as written in the brief) | {fmt(R_STAR*(2*f-1)/(1-f), 6)} SOL | "
            f"**does not give 30 SOL: inverted** |",
            f"| V_sol = R*(1−f)/(2f−1) (correct form) | {fmt(v_sol_from_r, 6)} SOL | gives 30.0009 SOL |",
            f"| FDV at graduation = R*/(1−f) | {fmt(R_STAR/(1-f), 4)} SOL | holds |",
            f"| market cap / reserve at graduation = 1/(1−f) | {fmt(1/(1-f), 4)}× | holds |",
            f"| opening → graduation price multiple = (f/(1−f))² | {fmt((f/(1-f))**2, 4)}× | holds when V_sol and V_tok "
            f"satisfy both closed forms |",
            f"| cost to lift the pool price +10% = (√1.1 − 1)·x | {(math.sqrt(1.1)-1)*100:.4f}% of the pool's SOL side x | "
            f"holds for any constant-product pool; independent of f |", ""]
    # parameter sets
    rows = []
    s, R, cp, pp, st = junction(F(30), V_TOK_PUMP, "tokens")
    rows.append(("pump.fun published: V_sol 30, V_tok 1,073,000,000, switch at s = fS", s, R, S-s, st))
    s, R, cp, pp, st = junction(F(30), V_TOK_BRIEF, "tokens")
    rows.append(("V_sol 30, V_tok 1,073,025,606, switch at s = fS", s, R, S-s, st))
    s, R, cp, pp, st = junction(F(30), V_TOK_BRIEF, "reserve")
    rows.append(("V_sol 30, V_tok 1,073,025,606, switch at R = 85 SOL (brief's trigger)", s, R, S-s, st))
    v_sol_chosen = R_STAR*(V_TOK_BRIEF-f*S)/(f*S)
    s, R, cp, pp, st = junction(v_sol_chosen, V_TOK_BRIEF, "reserve")
    rows.append((f"V_sol {fmt(v_sol_chosen, 9)} (derived so R = 85 at s = fS), V_tok 1,073,025,606, switch at R = 85",
                 s, R, S-s, st))
    s, R, cp, pp, st = junction(v_sol_from_r, v_tok_exact, "reserve")
    rows.append(("exact closed forms (V_sol, V_tok both exact), switch at R = 85", s, R, S-s, st))
    out += ["### Junction between curve and pool, by parameter set", "",
            "| parameters | tokens sold at switch | reserve at switch (SOL) | tokens left for the pool | price step |",
            "|---|---|---|---|---|"]
    for name, s, R, left, st in rows:
        out.append(f"| {name} | {fmt(s, 3)} | {fmt(R, 6)} | {fmt(left, 3)} | {float(st)*100:+.10f}% |")
    out.append("")
    # integer implementation of the chosen parameters
    v_sol_lamports = round(v_sol_chosen*LAMPORTS)
    v_tok_base = int(V_TOK_BRIEF*DEC)
    ic = integer_curve(v_sol_lamports, v_tok_base)
    out += ["### Chosen integer parameters (program units)", "",
            "| parameter | value |", "|---|---|",
            f"| V_sol | {v_sol_lamports:,} lamports ({fmt(F(v_sol_lamports, LAMPORTS), 9)} SOL) |",
            f"| V_tok | {v_tok_base:,} base units (1,073,025,606 tokens, 6 decimals) |",
            f"| K = V_sol·V_tok | {ic['K']:,} (fits u128: {ic['K'] < 2**128}) |",
            f"| R* | {85*LAMPORTS:,} lamports |",
            f"| q_g (largest q with R(q) ≤ R*) | {ic['q_g']:,} base units = {fmt(F(ic['q_g'], DEC), 6)} tokens |",
            f"| R(q_g) | {ic['R_qg']:,} lamports (R* − R(q_g) = {ic['unspent']} lamports) |",
            f"| room tokens left to seed the pool, S − q_g | {ic['seed_tokens']:,} base units = "
            f"{fmt(F(ic['seed_tokens'], DEC), 6)} tokens |",
            f"| price step at the switch (integer rounding) | {float(ic['step'])*100:+.12f}% |", ""]
    # graduation trigger raised by the graduation rent (owner ruling 2)
    rent = graduation_rent_lamports()
    T = 85*LAMPORTS+rent
    Kc = v_sol_lamports*v_tok_base
    U = 10**15
    Rf = lambda q: Kc//(v_tok_base-q)-v_sol_lamports
    q_t = v_tok_base-Kc//(T+v_sol_lamports+1)-1
    assert Rf(q_t) <= T < Rf(q_t+1)
    remaining = U-q_t
    curve_close = F(Kc, (v_tok_base-q_t)**2)
    lit_step = F(85*LAMPORTS, remaining)/curve_close-1
    seed = (85*LAMPORTS*(v_tok_base-q_t)**2)//Kc
    seed_step = F(85*LAMPORTS, seed)/curve_close-1
    # alternative: re-derive V_sol (V_tok fixed) so all remaining tokens seed continuously
    def alt_step(vs):
        k = vs*V_TOK_BRIEF*DEC
        y = F(k, vs+T)
        q = V_TOK_BRIEF*DEC-y
        return F(85*LAMPORTS, U-q)/(F(vs+T)/y)-1
    lo, hi = F(29*LAMPORTS), F(31*LAMPORTS)
    for _ in range(200):
        mid = (lo+hi)/2
        if alt_step(mid) > 0:
            lo = mid
        else:
            hi = mid
    vs_alt = round(lo)
    k_alt = vs_alt*v_tok_base
    q_alt = v_tok_base-k_alt//(T+vs_alt+1)-1
    alt_final = F(85*LAMPORTS, U-q_alt)/F(k_alt, (v_tok_base-q_alt)**2)-1
    out += ["### Graduation trigger raised to R* + graduation rent", "",
            "| quantity | value |", "|---|---|",
            f"| graduation rent (DAMM v2 accounts, from account_sizes.py) | {rent:,} lamports |",
            f"| trigger T = R* + rent | {T:,} lamports ({fmt(F(T, LAMPORTS), 9)} SOL) |",
            f"| q_g at T (largest q with R(q) ≤ T) | {q_t:,} base units = {fmt(F(q_t, DEC), 6)} tokens |",
            f"| R(q_g) | {Rf(q_t):,} lamports (T − R(q_g) = {T-Rf(q_t)}) |",
            f"| room tokens left in RoomVault, U − q_g | {remaining:,} base units |",
            f"| literal reading: seed R* with all remaining tokens, price step | {float(lit_step)*100:+.6f}% |",
            f"| chosen: seed R* with N = floor(R*·(V_tok − q_g)²/K) tokens | N = {seed:,} base units = "
            f"{fmt(F(seed, DEC), 6)} tokens |",
            f"| chosen: unsold tokens retired, U − q_g − N | {remaining-seed:,} base units = "
            f"{fmt(F(remaining-seed, DEC), 6)} tokens |",
            f"| chosen: price step (pool opens at or above the curve's closing price by < 1 base unit) | "
            f"{float(seed_step)*100:+.3e}% |",
            f"| alternative: re-derive V_sol (V_tok fixed) to seed all remaining tokens | V_sol = {vs_alt:,} lamports; "
            f"seed {U-q_alt:,} base units; step {float(alt_final)*100:+.12f}% |", ""]
    # price impact and depth on the chosen curve, in SOL
    K = v_sol_chosen*V_TOK_BRIEF
    Kp = R_STAR*F(seed, DEC)          # pool constant with the chosen seed (R* SOL, N tokens)
    def state(R):
        if R < R_STAR:
            x = v_sol_chosen+R
            return x, K/x, K
        x = R
        return x, Kp/x, Kp
    def impact(R, b):
        x, y, k = state(R)
        T_sol = F(T, LAMPORTS)
        if R < R_STAR and T_sol <= R+b:  # curve-phase row whose buy crosses graduation: the curve fills to T, the reserve hands R* to the
            x2 = R+b-F(rent, LAMPORTS)   # pool and the rent to GradPayer, so the pool's SOL side ends at R+b-rent
            return float((x2*x2/Kp)/(x*x/k)-1)
        return float(((x+b)**2)/(x*x)-1)
    out += ["### Price impact of a buy (marginal price after vs before; fees excluded)", "",
            "Curve phase below 85 SOL of reserve; pool phase from 85 SOL (the pool's SOL side x starts at R* = 85 "
            "and grows with net buying; K' = R* x N). Rows at and above 85 SOL are pool-phase. Pool fee excluded.", "",
            "| reserve / pool SOL side | buy 0.5 SOL | 5 SOL | 50 SOL | 500 SOL | FDV (SOL) | FDV / reserve |",
            "|---|---|---|---|---|---|---|"]
    for R in (F(1), F(10), F(50), F(84), F(85), F(500), F(5000), F(50000)):
        x, y, k = state(R)
        fdv = x/y*S
        cells = " | ".join(f"{impact(R, F(b))*100:,.2f}%" for b in (F(1, 2), 5, 50, 500))
        out.append(f"| {fmt(R, 0)} SOL | {cells} | {fmt(fdv, 0)} | {float(fdv/R):,.1f}× |")
    out += ["", "### Depth: SOL needed to move the price (fees excluded)", "",
            "| reserve / pool SOL side | +1% | +5% | +10% | −1% sale | −5% sale | −10% sale |",
            "|---|---|---|---|---|---|---|"]
    for R in (F(10), F(50), F(85), F(500), F(5000), F(50000)):
        x, y, k = state(R)
        up = [float(x)*(math.sqrt(1+u)-1) for u in (.01, .05, .10)]
        dn = [float(x)*(1-math.sqrt(1-u)) for u in (.01, .05, .10)]
        out.append(f"| {fmt(R, 0)} SOL | " + " | ".join(f"{v:,.3f}" for v in up+dn) + " |")
    out += ["", "In the curve phase x = V_sol + R includes the virtual SOL, so depth there is not backed by real SOL "
            "beyond R."]
    print("\n".join(out))


if __name__ == "__main__":
    main()
