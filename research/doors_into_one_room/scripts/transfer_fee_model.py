"""Arithmetic for the transfer-fee graduation path (no simulation, no market data).

Mechanics (verified in solana-program/token-2022 @ 986b3aa5):
  fee = min(ceil(amount * bps / 10_000), maximum_fee)    transfer_fee/mod.rs:58
  the recipient is credited amount - fee; the fee is withheld in the RECIPIENT
  token account (processor.rs ~575-586). Mint and burn charge no transfer fee.

Per swap in a pool where one side is the fee-bearing canonical token, exactly one
transfer of that token happens (user -> vault on a sell, vault -> user on a buy),
so the fee take is bps x the token notional of the swap. Multi-hop routes that
pass through the token as an intermediate pay twice.

Door-routed volume after graduation (DESIGN.md / GRADUATION doc): the program CPIs
the external pool and moves canonical tokens between the pool vault and its own
wrapper vault, so it also pays the transfer fee once per swap, plus the door
program's own trade fee (PERMANENT_CURVE_SPEC.md default 100 bps).
"""
VOLUME = 1_000_000.0
DOOR_FEE_BPS = 100
SPEC_SPLIT = dict(door_creator=0.30, room_founder=0.10, reserve=0.20, protocol=0.40)
LAMPORTS_PER_SIGNATURE = 5_000      # getFeeForMessage on mainnet, slot 463,694,000
USD_PER_SOL = 150.0
ACCOUNTS_PER_HARVEST_TX = 60         # 64-account lock limit minus mint, fee payer, program and margin


def money(x):
    return f"${x:,.0f}" if abs(x) >= 100 else f"${x:,.2f}"


def main():
    print("<!-- generated by scripts/transfer_fee_model.py -->")
    print("Per $1M of volume. Transfer-fee take is collected in the canonical token, withheld in recipient "
          "accounts; 'net in SOL' assumes the withheld tokens are later sold into the same pool, paying the "
          "transfer fee once more (price impact of that sale not included).\n")
    print("| transfer fee | raw pool volume: fee take (tokens) | raw pool: net in SOL after selling it | "
          "door-routed: transfer fee take | door-routed: door program fee (100 bps) | door-routed total | "
          "door-routed program fee, of which door creators / founder / reserve / protocol |\n|---|---|---|---|---|---|---|")
    for bps in (10, 30, 50, 100):
        r = bps/1e4
        take = r*VOLUME
        net = take*(1-r)
        door = DOOR_FEE_BPS/1e4*VOLUME
        split = " / ".join(money(door*v) for v in SPEC_SPLIT.values())
        print(f"| {bps} bps | {money(take)} | {money(net)} | {money(take)} | {money(door)} | "
              f"{money(take+door)} | {split} |")
    print("\nCost borne per $1M of raw pool volume by the people who pay it (same as the take): "
          "traders on every swap; a two-hop route through the token pays 2x.\n")
    print("LP round trip on the fee-bearing side (deposit, later withdraw), as a fraction of the token-side "
          "amount: about 2 x rate.\n")
    print("| transfer fee | LP round-trip cost on a $10k position (half in the token) | "
          "turnover (volume / TVL) needed to repay it if LPs keep an illustrative 25 bps of each swap |\n|---|---|---|")
    for bps in (10, 30, 50, 100):
        r = bps/1e4
        cost = 2*r*5_000
        print(f"| {bps} bps | {money(cost)} | {cost/10_000/0.0025:.1f}x TVL over the holding period |")
    print("\nHarvest cost (permissionless HarvestWithheldTokensToMint, one signature per transaction):\n")
    print("| token accounts holding withheld fees | transactions | base fees (SOL) | USD |\n|---|---|---|---|")
    for n in (1_000, 100_000, 1_000_000):
        tx = -(-n//ACCOUNTS_PER_HARVEST_TX)
        sol = tx*LAMPORTS_PER_SIGNATURE/1e9
        print(f"| {n:,} | {tx:,} | {sol:,.6f} | {money(sol*USD_PER_SOL)} |")
    print("\nPriority fees and the RPC cost of finding the accounts (a full scan of the mint's token accounts) "
          "are not included.")


if __name__ == "__main__":
    main()
