"""Fee split per $1M of volume (60% door / 40% protocol, no founder), and door-spam economics with
free launches (door_fee_lamports = room_fee_lamports = 0: a door costs only its rent).

Spam model (an assumption, not measured): a door with no traffic of its own earns only from buyers
who pick among a room's doors uniformly (random, confused, or an unranked list). If a share rho of
room volume V picks uniformly across D doors, each such door earns door_rate * rho * V / D.
A spammer opening m doors in a room that already has D doors earns door_rate * rho * V * m / (D + m)
and pays m * rent (rent is never refunded: doors are never closed). rho is unknown and swept.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from account_sizes import per_door_rent_lamports, graduation_rent_lamports  # noqa: E402

USD_PER_SOL = 150.0                       # used only to express SOL figures in dollars
RENT_PER_DOOR_SOL = per_door_rent_lamports()/1e9
GRAD_RENT_SOL = graduation_rent_lamports()/1e9

FEE_BPS = 100
DOOR_SHARE = 0.60
PROTOCOL_SHARE = 0.40
DOOR_FEE_SOL = 0.0                         # default: free
ROOM_FEE_SOL = 0.0                         # default: free


def money(x):
    if abs(x) >= 1e6: return f"${x/1e6:,.2f}M"
    if abs(x) >= 1e3: return f"${x/1e3:,.1f}k"
    return f"${x:,.2f}"


def main():
    rate = FEE_BPS/1e4
    door_rate = rate*DOOR_SHARE
    rent_usd = RENT_PER_DOOR_SOL*USD_PER_SOL
    print("<!-- generated by scripts/fee_model.py -->")
    print(f"Trade fee {FEE_BPS} bps on every buy and sell, charged on top of the trade.\n")
    print("| route | to the door | to the reserve | to the protocol | total |\n|---|---|---|---|---|")
    print(f"| through door N, per $1M | {money(door_rate*1e6)} | $0 | {money(rate*PROTOCOL_SHARE*1e6)} | "
          f"{money(rate*1e6)} |")
    print(f"| room token through the program, per $1M | $0 | {money(door_rate*1e6)} | "
          f"{money(rate*PROTOCOL_SHARE*1e6)} | {money(rate*1e6)} |\n")
    print(f"Door fee {DOOR_FEE_SOL} SOL and room fee {ROOM_FEE_SOL} SOL (defaults). A door costs its rent only: "
          f"{RENT_PER_DOOR_SOL:.6f} SOL = {money(rent_usd)}. Graduation rent ({GRAD_RENT_SOL:.6f} SOL) is paid "
          f"from the reserve at graduate, not by the launcher.\n")
    print("Room lifetime volume at which one more no-traffic door repays its rent, "
          "V = rent × (D + 1) / (door_rate × rho):\n")
    print("| rho | D = 10 | D = 100 | D = 1,000 | D = 10,000 |\n|---|---|---|---|---|")
    for rho in (0.01, 0.05, 0.3):
        cells = [money(rent_usd*(D+1)/(door_rate*rho)) for D in (10, 100, 1000, 10000)]
        print(f"| {rho} | " + " | ".join(cells) + " |")
    print("\nIncome of one more no-traffic door over the room's life, net of its rent, door_rate × rho × V / (D + 1) "
          "− rent:\n")
    print("| room lifetime volume V | rho | D = 10 | D = 100 | D = 1,000 | D = 10,000 |\n|---|---|---|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            cells = [money(door_rate*rho*V/(D+1)-rent_usd) for D in (10, 100, 1000, 10000)]
            print(f"| {money(V)} | {rho} | " + " | ".join(cells) + " |")
    m, D = 10_000, 10
    print(f"\n{m:,} spam doors in a room with {D} doors already (cost = rent only):\n")
    print("| V | rho | spam income | spam cost (rent) | net |\n|---|---|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            inc = door_rate*rho*V*m/(D+m)
            cost = m*rent_usd
            print(f"| {money(V)} | {rho} | {money(inc)} | {money(cost)} | {money(inc-cost)} |")


if __name__ == "__main__":
    main()
