"""Fee split per $1M of volume (60% door / 40% protocol, no founder) and door-spam economics.

Spam model (an assumption, not measured): a door with no traffic of its own earns only from
buyers who pick among a room's doors uniformly. If a share rho of room volume V picks uniformly
across D doors, each such door earns door_rate * rho * V / D. A spammer opening m doors in a room
that already has D doors earns door_rate * rho * V * m / (D + m) and pays m * (door_fee + rent).
rho is unknown and swept.
"""
USD_PER_SOL = 150.0                       # used only to express SOL figures in dollars
RENT_PER_DOOR_SOL = 13_565_040/1e9         # outputs/account_sizes.md (max metadata)
GRAD_RENT_SOL = 24_680_160/1e9             # outputs/account_sizes.md

FEE_BPS = 100
DOOR_SHARE = 0.60
PROTOCOL_SHARE = 0.40
DOOR_FEE_SOL = 0.5
DOOR_FEE_RESERVE = 0.60
ROOM_FEE_SOL = 1.0


def money(x):
    if abs(x) >= 1e6: return f"${x/1e6:,.2f}M"
    if abs(x) >= 1e3: return f"${x/1e3:,.1f}k"
    return f"${x:,.2f}"


def main():
    rate = FEE_BPS/1e4
    door_rate = rate*DOOR_SHARE
    print("<!-- generated by scripts/fee_model.py -->")
    print(f"Trade fee {FEE_BPS} bps on every buy and sell, charged on top of the trade.\n")
    print("| route | to the door | to the reserve | to the protocol | total |\n|---|---|---|---|---|")
    print(f"| through door N, per $1M | {money(door_rate*1e6)} | $0 | {money(rate*PROTOCOL_SHARE*1e6)} | "
          f"{money(rate*1e6)} |")
    print(f"| room token through the program, per $1M | $0 | {money(door_rate*1e6)} | "
          f"{money(rate*PROTOCOL_SHARE*1e6)} | {money(rate*1e6)} |\n")
    print(f"Door fee {DOOR_FEE_SOL} SOL: {DOOR_FEE_RESERVE*DOOR_FEE_SOL:.2f} SOL to the reserve, "
          f"{(1-DOOR_FEE_RESERVE)*DOOR_FEE_SOL:.2f} SOL to the protocol; plus rent {RENT_PER_DOOR_SOL:.6f} SOL "
          f"(cost to the opener {DOOR_FEE_SOL+RENT_PER_DOOR_SOL:.6f} SOL = {money((DOOR_FEE_SOL+RENT_PER_DOOR_SOL)*USD_PER_SOL)}).")
    print(f"Room fee {ROOM_FEE_SOL} SOL: {GRAD_RENT_SOL:.6f} SOL into GradPayer for the DAMM v2 accounts, "
          f"{ROOM_FEE_SOL-GRAD_RENT_SOL:.6f} SOL to the protocol.\n")
    print("Break-even door fee for one more no-traffic door, door_rate × rho × V / (D + 1), in USD:\n")
    print("| room lifetime volume V | rho | D = 10 | D = 100 | D = 1,000 | D = 10,000 |\n|---|---|---|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            cells = [money(door_rate*rho*V/(D+1)) for D in (10, 100, 1000, 10000)]
            print(f"| {money(V)} | {rho} | " + " | ".join(cells) + " |")
    m, D = 10_000, 10
    print("\n10,000 spam doors in a room with 10 honest doors:\n")
    print("| V | rho | spam income | cost, rent only | cost, 0.5 SOL fee + rent | "
          "minimum door fee on top of rent to make it unprofitable (SOL) |\n|---|---|---|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            inc = door_rate*rho*V*m/(D+m)
            need = max(0.0, door_rate*rho*V/(D+m)/USD_PER_SOL-RENT_PER_DOOR_SOL)
            print(f"| {money(V)} | {rho} | {money(inc)} | {money(m*RENT_PER_DOOR_SOL*USD_PER_SOL)} | "
                  f"{money(m*(DOOR_FEE_SOL+RENT_PER_DOOR_SOL)*USD_PER_SOL)} | {need:.4f} |")


if __name__ == "__main__":
    main()
