"""Fee split per $1M of room volume, and the door fee at which door spam stops paying.

Spam model (an assumption, not measured): a door with no traffic of its own earns
only from buyers who pick among a room's doors uniformly (random, confused, or a
frontend listing doors without ranking). If a share rho of room volume V picks
uniformly across D doors, each such door earns creator_rate * rho * V / D over the
room's life. A spammer opening m doors in a room that already has D doors earns
creator_rate * rho * V * m / (D + m) and pays m * (door_fee + rent).
rho is unknown; the shared-narrative simulation assumed 0.3. It is swept here.
"""
USD_PER_SOL = 150.0
RENT_PER_DOOR_SOL = 9_166_320/1e9          # from outputs/account_sizes.md (max metadata)

FEE_BPS = 100
SPLIT = dict(door_creator=3000, room_founder=1000, reserve=2000, protocol=4000)   # bps of the fee
DOOR_FEE_SOL = 0.5
DOOR_FEE_SPLIT = dict(reserve=5000, room_founder=1000, protocol=4000)
assert sum(SPLIT.values()) == 10_000 and sum(DOOR_FEE_SPLIT.values()) == 10_000


def money(x):
    if abs(x) >= 1e6: return f"${x/1e6:,.2f}M"
    if abs(x) >= 1e3: return f"${x/1e3:,.1f}k"
    return f"${x:,.2f}"


def main():
    creator_rate = FEE_BPS/1e4*SPLIT["door_creator"]/1e4
    print("<!-- generated by scripts/fee_model.py -->")
    print(f"Trade fee {FEE_BPS} bps on every buy and sell, charged on top of the curve amount.\n")
    print("| party | share of fee | rate on volume | per $1M of room volume |\n|---|---|---|---|")
    for k, v in SPLIT.items():
        rate = FEE_BPS/1e4*v/1e4
        print(f"| {k} | {v/100:.0f}% | {rate*100:.2f}% | {money(rate*1e6)} |")
    print(f"| total | 100% | {FEE_BPS/100:.2f}% | {money(FEE_BPS/1e4*1e6)} |\n")
    print(f"Door fee {DOOR_FEE_SOL} SOL (${DOOR_FEE_SOL*USD_PER_SOL:,.0f}) plus rent {RENT_PER_DOOR_SOL:.6f} SOL "
          f"(${RENT_PER_DOOR_SOL*USD_PER_SOL:,.2f}); split of the door fee: "
          + ", ".join(f"{k} {v/100:.0f}%" for k, v in DOOR_FEE_SPLIT.items()) + ".\n")
    print("Break-even door fee for one additional no-traffic door, "
          "= creator_rate × rho × V / (D + 1), in USD:\n")
    print("| room lifetime volume V | rho | D = 10 doors | D = 100 | D = 1,000 | D = 10,000 |\n|---|---|---|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            cells = [money(creator_rate*rho*V/(D+1)) for D in (10, 100, 1000, 10000)]
            print(f"| {money(V)} | {rho} | " + " | ".join(cells) + " |")
    print("\n10,000 spam doors in one room (D = 10 honest doors already there):\n")
    print("| V | rho | spam income (all 10,000) | cost at rent only | cost at 0.5 SOL fee + rent |\n|---|---|---|---|---|")
    m, D = 10_000, 10
    for V in (1e6, 10e6, 50e6):
        for rho in (0.05, 0.3):
            inc = creator_rate*rho*V*m/(D+m)
            print(f"| {money(V)} | {rho} | {money(inc)} | {money(m*RENT_PER_DOOR_SOL*USD_PER_SOL)} | "
                  f"{money(m*(DOOR_FEE_SOL+RENT_PER_DOOR_SOL)*USD_PER_SOL)} |")
    print("\nMinimum door fee (SOL, on top of rent) that makes a 10,000-door attack unprofitable:\n")
    print("| V | rho = 0.05 | rho = 0.3 |\n|---|---|---|")
    for V in (1e6, 10e6, 50e6):
        cells = []
        for rho in (0.05, 0.3):
            per = creator_rate*rho*V/(D+m)/USD_PER_SOL - RENT_PER_DOOR_SOL
            cells.append(f"{max(0.0, per):.4f}")
        print(f"| {money(V)} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
