"""Regenerate the spec's measured-CU block from executed SBF test evidence.

No fallback estimates: absent or incomplete runtime evidence is an error.
"""
import json
from pathlib import Path

HERE=Path(__file__).resolve().parents[1]
SPEC=HERE.parent/'research/doors_into_one_room/PERMANENT_CURVE_SPEC.md'
def main():
    report=json.loads((HERE/'verification/svm_report.json').read_text())
    build=json.loads((HERE/'verification/build.json').read_text())
    packets=json.loads((HERE/'verification/packets.json').read_text())
    assert report['property_iterations']>=10000
    cap=build['writable_account_limit']['units']
    lines=['<!-- generated by program/scripts/report_cu.py from executed SBF tests -->',
           'Curve-phase Anchor SBF execution in LiteSVM, with real SPL CPIs and',
           'transaction signature verification. These are execution-CU measurements,',
           'not observed cluster throughput. CU comes from the runtime’s inclusive',
           'program log, including its CPIs and excluding the separate compute-budget',
           'instruction. Standalone ATA creation and network scheduling are excluded.',
           'The test VM is LiteSVM 0.18.1 with its locked Agave 4.3.2 runtime;',
           'the build target/CLI is current stable Solana 4.4.0.',
           '',f'Writable-account cap: {cap:,} CU, verified from Agave v4.4.0 source.',
           '**These are observed values from one runtime, not bounds.** LiteSVM 0.18.1 (Agave 4.3.2), fixed',
           'fixture addresses. Live runs exceed them: on the Agave 4.4.0 local validator, `convert` and',
           '`claim_door_fees` used 5,773 and 4,500 CU more than the maxima below (program/docs/DEPLOYMENT.md',
           '§7), and PDA bump searches vary with every address. Budget with margin above them.',
           '', '| instruction / route | samples | observed min CU | observed max CU | per room/block at the observed max (not a guarantee) |',
           '|---|---:|---:|---:|---:|']
    measured={}
    for key in ['buy_door','sell_door','buy_room','sell_room','convert','open_door']:
        samples=report['cu'][key]['samples']+packets['edge_cu_samples'].get(key,[])
        row={'count':len(samples),'min':min(samples),'max':max(samples)};measured[key]=row
        lines.append(f"| {key} | {row['count']:,} | {row['min']:,} | {row['max']:,} | {cap//row['max']:,} |")
    lines+=['',f"The property run executes {report['property_iterations']:,} mixed iterations and",
        'asserts full global liability coverage, token conservation, authority revocation',
        'and exact ReserveVault/state deltas after affected instructions. Additional',
        'samples exercise maximum-length room/door metadata, a larger curve position,',
        'the capped crossing buy and conversion while complete. These are maxima',
        'observed in these fixtures, not an upper bound for any address or runtime.',
        '',f"Maximum-metadata creation with an atomic first buy: legacy {packets['legacy_bytes']:,} bytes",
        f"exceeds the {packets['packet_limit']:,}-byte packet limit; the executed v0 transaction",
        f"uses {packets['v0_bytes']:,} bytes. Its whole-transaction CU is {packets['transaction_cu']:,}.",
        '', 'The last column is floor(cap / observed maximum execution CU). Actual scheduling',
        'also charges signatures, write locks, instruction data and the transaction’s',
        'requested compute budget. Clients must size that budget; these counts are',
        'not a promise of accepted transactions per block. Pool-phase CU is unmeasured.',
        '',f"Build commit: `{build['git_commit']}`; ELF SHA-256: `{build['elf_sha256']}`.",
        'Raw samples/statistics, tool versions and source hashes are in',
        '`program/verification/svm_report.json` and `program/verification/build.json`.', '']
    block='\n'.join(lines)
    start='<!-- BEGIN GENERATED PROGRAM CU -->';end='<!-- END GENERATED PROGRAM CU -->'
    text=SPEC.read_text(encoding='utf-8')
    if start in text:
        before,tail=text.split(start,1);_,after=tail.split(end,1);text=before+start+'\n'+block+end+after
    else:
        anchor='**Door count.**';assert anchor in text;text=text.replace(anchor,start+'\n'+block+end+'\n\n'+anchor,1)
    SPEC.write_text(text,encoding='utf-8',newline='\n')
    (HERE/'verification/cu.md').write_text(block,encoding='utf-8',newline='\n')
    trade_max=max(measured[k]['max'] for k in ['buy_door','sell_door','buy_room','sell_room','convert'])
    print(f'Generated CU report; maximum measured trade = {trade_max:,} CU. Assumed baseline in brief = 60,000 CU.')
    if trade_max>120000:
        print('STOP: trade exceeds twice the brief’s baseline. Owner decision required before optimization.')
        raise SystemExit(2)
if __name__=='__main__':main()
