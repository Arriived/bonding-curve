"""Check the emitted Anchor IDL's packed Borsh layout against the build spec.

This checks every field's order, offset and width, not native Rust alignment.
Run after anchor idl build; no RPC or third-party Python packages required.
"""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'research/doors_into_one_room/scripts'))
import account_sizes as A

def main():
    idl=json.loads((ROOT/'program/target/idl/doors_v1.json').read_text())
    def normal(name):return name.split('::')[-1].replace('_','').lower()
    types={normal(t['name']):t['type'] for t in idl['types']}
    def size(ty):
        if isinstance(ty,str):return {'u8':1,'bool':1,'u16':2,'u32':4,'u64':8,'i64':8,'u128':16,'pubkey':32}[ty]
        if 'array' in ty:return size(ty['array'][0])*ty['array'][1]
        if 'defined' in ty:
            name=ty['defined'];name=name['name'] if isinstance(name,dict) else name
            return sum(size(f['type']) for f in types[normal(name)]['fields'])
        raise ValueError(ty)
    layouts = dict(A.LAYOUTS)
    # The prototype extends packed accounts after the deployed layouts.
    if "virtual_quote" in [field["name"] for field in types["door"]["fields"]]:
        layouts["Room"] = [*layouts["Room"], ("protocol_accrued_room", 8)]
        layouts["Door"] = [*layouts["Door"], ("virtual_quote", 16), ("sold", 8), ("accrued_room", 8)]
    out={}
    for name in ['Config','Room','Door','SlugLock','NameLock','PendingGate']:
        actual=types[normal(name)]['fields'];expected=layouts[name][1:];assert len(actual)==len(expected),(name,len(actual),len(expected))
        rows=[];offset=8
        for field,(label,n) in zip(actual,expected):
            expected_name=label.split(':')[0];assert normal(field['name'])==normal(expected_name),(name,field['name'],label)
            assert size(field['type'])==n,(name,field,n)
            rows.append({'field':field['name'],'offset':offset,'bytes':n});offset+=n
        out[name]={'bytes':offset,'fields':rows};assert offset==sum(n for _,n in layouts[name])
    path=ROOT/'program/verification/layouts.json';path.write_text(json.dumps(out,indent=2)+'\n',encoding='utf-8',newline='\n')
    def leaves(accounts):
        return [leaf for a in accounts for leaf in (leaves(a['accounts']) if 'accounts' in a else [a])]
    contexts={}
    rows=['<!-- generated by program/scripts/check_layouts.py from the emitted Anchor IDL -->',
          'Actual curve-phase instruction contexts include vaults needed for the',
          'end-of-instruction assertions. Counts include all optional account metas;',
          'an absent optional uses the program-ID sentinel, reducing unique keys.',
          'These are meta counts, not legacy/v0 packet-size measurements.',
          '', '| instruction | metas with optionals | writable metas | signers |',
          '|---|---:|---:|---:|']
    for instruction in idl['instructions']:
        fields=leaves(instruction['accounts']);name=instruction['name']
        count={'metas_with_optionals':len(fields),'writable':sum(bool(f.get('writable')) for f in fields),'signers':sum(bool(f.get('signer')) for f in fields)}
        contexts[name]=count;rows.append(f"| {name} | {count['metas_with_optionals']} | {count['writable']} | {count['signers']} |")
        if normal(name)=='createroom':
            config=next(f for f in fields if normal(f['name'])=='config');assert not config.get('writable',False),'permissionless creation must not write Config'
    (ROOT/'program/verification/instruction_contexts.json').write_text(json.dumps(contexts,indent=2)+'\n',encoding='utf-8',newline='\n')
    spec=ROOT/'research/doors_into_one_room/PERMANENT_CURVE_SPEC.md';text=spec.read_text(encoding='utf-8')
    start='<!-- BEGIN GENERATED PROGRAM CONTEXTS -->';end='<!-- END GENERATED PROGRAM CONTEXTS -->';block='\n'.join(rows)+'\n'
    if start in text:
        before,tail=text.split(start,1);_,after=tail.split(end,1);text=before+start+'\n'+block+end+after
    else:
        marker='**Room write lock.**';text=text.replace(marker,start+'\n'+block+end+'\n\n'+marker,1)
    spec.write_text(text,encoding='utf-8',newline='\n')
    print('IDL field order, widths and offsets match all authoritative packed layouts:',{k:v['bytes'] for k,v in out.items()})
if __name__=='__main__':main()
