"""Reproduce pre-build invariant conflicts algebraically, without a deployed VM.

Transfer/burn semantics are sourced from the official Token-2022 documentation.
This is not a CU measurement or a substitute for the requested SBF tests.
"""
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = 'de1f7fd'
OUT = ROOT / 'program/verification'


def main():
    curve=json.loads((ROOT/'research/doors_into_one_room/outputs/curve_quantities.json').read_text(encoding='utf-8'))
    supply=1_000_000_000*10**6  # fixed premint and decimals specified in section 1
    gross=101;fee_bps=100
    net=gross*10_000//(10_000+fee_bps)
    virtual_sol=curve['v_sol_lamports'];virtual_tokens=curve['v_tok_base'];k=curve['K']
    sold=virtual_tokens-k//(virtual_sol+net+1)-1
    reserve=lambda q:k//(virtual_tokens-q)-virtual_sol
    assert 0<sold<supply and reserve(sold)<=net<reserve(sold+1)
    room_vault=supply-sold;door_vault=supply-sold;door_backing=sold
    assert sold==supply-room_vault and door_backing==supply-door_vault
    cases=[
        {'case':'one door token unit returned directly to DoorVault',
         'invariant':'B1: DoorRoomVault == U - DoorVault',
         'before_lhs':door_backing,'before_rhs':supply-door_vault,
         'after_lhs':door_backing,'after_rhs':supply-(door_vault+1)},
        {'case':'one room token unit returned directly to RoomVault (room-token route)',
         'invariant':'S1: sold == U - RoomVault',
         'before_lhs':sold,'before_rhs':supply-room_vault,
         'after_lhs':sold,'after_rhs':supply-(room_vault+1)},
        {'case':'holder burns one door token unit',
         'invariant':'M1: mint.supply == U at all times',
         'before_lhs':supply,'before_rhs':supply,
         'after_lhs':supply-1,'after_rhs':supply},
    ]
    for case in cases:
        assert case['before_lhs']==case['before_rhs']
        assert case['after_lhs']!=case['after_rhs']
    original=subprocess.run(['git','show',BASELINE+':research/doors_into_one_room/PERMANENT_CURVE_SPEC.md'],cwd=ROOT,capture_output=True,check=True).stdout
    result={'kind':'algebraic reproduction of the original spec conflict; corrected policy is approved; not SBF execution',
        'original_spec_commit':BASELINE,'original_spec_sha256':hashlib.sha256(original).hexdigest(),
        'inputs':{'initial_supply':supply,'gross_buy_lamports':gross,'fee_bps':fee_bps,
                  'net_buy_lamports':net,'sold_base_units':sold},
        'sources':['https://solana.com/docs/tokens/basics/transfer-tokens',
                   'https://solana.com/docs/tokens/basics/burn-tokens'],
        'cases':cases}
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/'spec_conflicts.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8',newline='\n')
    lines=['<!-- generated by program/scripts/check_spec_conflicts.py -->',
           '# Pre-build invariant counterexamples','',
           'These are algebraic examples using the spec’s own integer curve, not program execution or measured CU.',
           'The donor/holder signs the standard Token-2022 transfer or burn. No launchpad instruction runs, '
           'so its cached sold/backing fields do not change. Transfer destinations need not sign.','',
           f'Fixture: gross buy {gross} lamports, net {net}, output {sold} base units; initial mint supply {supply}.','',
           '| operation | invariant | equality before | equality after |',
           '|---|---|---|---|']
    for case in cases:
        lines.append(f'| {case["case"]} | {case["invariant"]} | {case["before_lhs"]} = {case["before_rhs"]} | {case["after_lhs"]} != {case["after_rhs"]} |')
    lines+=['','The same unsolicited-transfer issue applies to room tokens sent directly into DoorRoomVault.',
            '', '[Official transfer semantics](https://solana.com/docs/tokens/basics/transfer-tokens); '
            '[official burn semantics](https://solana.com/docs/tokens/basics/burn-tokens).', '']
    (OUT/'spec_conflicts.md').write_text('\n'.join(lines),encoding='utf-8',newline='\n')
    print(json.dumps(result['inputs']));print('All preconditions hold; every listed external operation breaks its quoted exact invariant.')


if __name__=='__main__':main()
